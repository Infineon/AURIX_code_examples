#define Baudrate_115200                     0x015B  //prescaler of 1
#define Baudrate_20000                      0x07D0  //prescaler of 1
#define Baudrate_19200                      0x0823  //prescaler of 1
#define Baudrate_9600                       0x0823  //prescaler of 2
#define Baudrate_4800                       0x0823  //prescaler of 4
#define Baudrate_2400                       0x0823  //prescaler of 8
