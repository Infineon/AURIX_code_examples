/* this function configure the UART module of the SCR */
void scr_uart_config(void)
{
    IfxScrUART_Config g_scrUARTconf;

    g_scrUARTconf.TxPin = TX_UART_PIN;
    g_scrUARTconf.RxPin = RX_UART_PIN;
    g_scrUARTconf.baudrate = Baudrate_115200;
    g_scrUARTconf.prescaler = IfxScrUART_fPCLK;             /* Prescaler should be changed according to the Baudrate, default 1 */

    /* Reset the buffer index and buffer size for RX and TX*/
    g_scrUARThandler.indRx = 0;
    g_scrUARThandler.indTx = 0;
    g_scrUARThandler.sizemRx = 0;
    g_scrUARThandler.sizemTx = 0;

    /* Pin configuration */
    scr_init_uartPin(&g_scrUARTconf);

    /* UART configuration */
    SCR_SCU_PAGE = 0;
    /* Fill baudrate buffer and prescaler */
    SCR_UART_BCON &= 0xF0;
    SCR_UART_BCON |= (uint8) g_scrUARTconf.prescaler;
    SCR_UART_BGL = (uint8) (g_scrUARTconf.baudrate & 0xFF);
    SCR_UART_BGH = (uint8) ((g_scrUARTconf.baudrate >> 8) & 0xFF);
    SCR_UART_BCON |= 0x01;

    /* Mode selection */
    SCR_UART_SCON &= 0xEF;
    SCR_UART_SCON = 0x40;
    SCR_UART_SCON |= 0x10;

    /* Interrupt configuration */
    SCR_SCU_PAGE = 0;
    SCR_IEN0 |= 0x10;
}

/*This is the UART interrupt function, it will clear the flag upon transmitting or receiving data
 * If a message byte is transmit the interrupt will transmit the next Byte
 * If a message byte is received the interrupt will receive the next Byte*/
void uartIsrHandler(void) __interrupt (XINTR4)
{
    unsigned char ioPage, scuPage;
    scuPage = SCR_SCU_PAGE;
    SCR_SCU_PAGE = 0;
    ioPage = SCR_IO_PAGE;
    SCR_IO_PAGE = 0;

    if(SCR_UART_SCON & 0x01)
    {
        SCR_UART_SCON &= 0xFE;
        if(g_scrUARThandler.indRx < g_scrUARThandler.sizemRx)
        {
            g_scrUARThandler.g_rxBuffer[g_scrUARThandler.indRx] = SCR_UART_SBUF;
            g_scrUARThandler.indRx ++;
        }
    }

    if(SCR_UART_SCON & 0x02)
    {
        SCR_UART_SCON &= 0xFD;
        if(g_scrUARThandler.indTx < g_scrUARThandler.sizemTx)
        {
            SCR_UART_SBUF = (uint8) g_scrUARThandler.g_txBuffer[g_scrUARThandler.indTx];
            g_scrUARThandler.indTx ++;
        }
    }
    SCR_IO_PAGE = ioPage;
    SCR_SCU_PAGE = scuPage;
}

/* This function configure Tx and Rx Pin for the UART Module
 * nb: make sure that the same Pin are not used for Tx and Rx */
void scr_init_uartPin(IfxScrUART_Config *uartConf)
{
    IfxScrUART_Pin txP = uartConf->TxPin;
    IfxScrUART_Pin rxP = uartConf->RxPin;

    if(txP == IfxScrUART_TXP00_0)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P00_IOCR0 = ScrPortMode_outputPushPullAlt1;
        SCR_IO_PAGE = 0;
        SCR_IO_P00_OUT |= ScrIoPin0;
    }
    if(txP == IfxScrUART_TXP00_7)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P00_IOCR7 = ScrPortMode_outputPushPullAlt2;
        SCR_IO_PAGE = 0;
        SCR_IO_P00_OUT |= ScrIoPin7;
    }
    if(txP == IfxScrUART_TXP01_1)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR1 = ScrPortMode_outputPushPullAlt1;
        SCR_IO_PAGE = 0;
        SCR_IO_P01_OUT |= ScrIoPin1;
    }
    if(txP == IfxScrUART_TXP01_4)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR4 = ScrPortMode_outputPushPullAlt1;
        SCR_IO_PAGE = 0;
        SCR_IO_P01_OUT |= ScrIoPin4;
    }
    if(txP == IfxScrUART_TXP01_6)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR6 = ScrPortMode_outputPushPullAlt1;
        SCR_IO_PAGE = 0;
        SCR_IO_P01_OUT |= ScrIoPin6;
    }
    if(rxP == IfxScrUART_RXP00_4)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P00_IOCR4 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF2;
    }
    if(rxP == IfxScrUART_RXP01_0)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR0 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF3;
    }
    if(rxP == IfxScrUART_RXP01_2)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR2 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF0;
    }
    if(rxP == IfxScrUART_RXP01_4)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR4 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF6;
    }
    if(rxP == IfxScrUART_RXP01_5)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR5 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF1;
    }
    if(rxP == IfxScrUART_RXP01_7)
    {
        SCR_IO_PAGE = 1;
        SCR_IO_P01_IOCR7 = ScrPortMode_inputNoPullDevice;
        SCR_SCU_PAGE = 2;
        SCR_SCU_MODPISEL0 = 0xF4;
    }
}

/*This function will transmit the data in pTxBuffer of size sizeT (blocking)*/
void scr_uart_transmit(uint8 *pTxBuffer, uint8 sizeT)
{
    if(sizeT <= Max_Buffer_Size)
    {
        SCR_SCU_PAGE = 0;
        g_scrUARThandler.indTx = 0;
        g_scrUARThandler.sizemTx = sizeT;
        for(uint8 i = 0; i < g_scrUARThandler.sizemTx; i++)
        {
            g_scrUARThandler.g_txBuffer[i] = (uint8) pTxBuffer[i];
        }
        /* write the first message bytes */
        SCR_UART_SBUF = (uint8) g_scrUARThandler.g_txBuffer[g_scrUARThandler.indTx];
        g_scrUARThandler.indTx ++;
        /* wait until or the Bytes are send in the interrupts */
        while(g_scrUARThandler.indTx < g_scrUARThandler.sizemTx)
        {}
    }
}

/*This function will receive data of size sizeR and store it into pRxBuffer (blocking)*/
void scr_uart_receive(uint8 *pRxBuffer, uint8 sizeR)
{
    if(sizeR <= Max_Buffer_Size)
    {
        SCR_SCU_PAGE = 0;
        g_scrUARThandler.indRx = 0;
        g_scrUARThandler.sizemRx = sizeR;
        /* wait until the message is received in the interrupt */
        while(g_scrUARThandler.indRx < g_scrUARThandler.sizemRx)
        {}
        /* read the data from the UART received buffer */
        for(uint8 i = 0; i < g_scrUARThandler.sizemRx; i++)
        {
            pRxBuffer[i] = (uint8)g_scrUARThandler.g_rxBuffer[i];
        }
    }
}
