void scr_basic_conf(IfxScrCLK_Div Cdiv, uint8 Pcon)
{
    /* set Pclk clock to 1Mhz, Base clock for timer2
     *  DIV     =  0    => Sys clock (20Mhz) divided by 5
     *  OSCWAKE =  1    => Sys clock at 100Mhz enabled
     */
    SCR_PASSWD = 0x98;
    SCR_SCU_PAGE = 1;
    SCR_SCU_CMCON = (Cdiv);
    SCR_PASSWD = 0xA8;

    SCR_IO_PAGE = 2;
    /* Enable all P00 and P01 pins */
    SCR_IO_P00_PDISC = 0x00;
    SCR_IO_P01_PDISC = 0x00;

    SCR_SCU_PAGE = 1;
    SCR_SCU_PMCON1 = Pcon;
    /* Clear NMI */
    SCR_SCU_NMISR = 0x00;
}

void scr_enable_int(void)
{
    SCR_SCU_PAGE = 0;
    /* Clear interrupt*/
    SCR_SCU_IRCON0 = 0x0;
    SCR_SCU_IRCON1 = 0x0;
    SCR_SCU_IRCON2 = 0x0;
    SCR_IEN0 |= 0x80;
}
