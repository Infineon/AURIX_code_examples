#ifndef SCR_GENERICDEFS_H
#define SCR_GENERICDEFS_H

#include "registers.h"

#define SCR_ISR __isr;
#define SFR(X) (*(__near volatile uint8*)(X))


/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#ifndef TRUE
#define TRUE  1
#endif

#ifndef FALSE
#define FALSE 0
#endif

#define SCR_INLINE      static inline

/*********************************************************************************************************************/
/*--------------------------------------------------Data Structures--------------------------------------------------*/
/*********************************************************************************************************************/
typedef signed char     sint8;      /*        -128 .. +127          */
typedef unsigned char   uint8;      /*           0 .. 255           */
typedef signed short    sint16;     /*      -32768 .. +32767        */
typedef unsigned short  uint16;     /*           0 .. 65535         */
typedef signed long     sint32;     /* -2147483648 .. +2147483647   */
typedef unsigned long   uint32;     /*           0 .. 4294967295    */
typedef long long       uint64;     /*           0 .. 4294967295    */
typedef float           float32;

typedef unsigned char   boolean;    /* for use with TRUE/FALSE */

typedef unsigned char   Scr_UReg_8Bit;
typedef signed char     Scr_SReg_8Bit;

#endif
