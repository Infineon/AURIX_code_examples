#include "scr_basicC.h"
#include <stdint.h>
#include "uart.h"
/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define Message_Size                 9
/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
uint8 txmBuffer[Message_Size];
uint8 rxmBuffer[Message_Size];

/*********************************************************************************************************************/
/*----------------------------------------------Function Implementations---------------------------------------------*/
/*********************************************************************************************************************/

void main(void)
{
    uint8 mask =(uint8) ~(LIN_DIS | RTC_DIS);
    scr_basic_conf(IfxScr_clkDiv_5, mask);

/*********************************************************************************************************************/
/*------------------------------------------------UART configuration-------------------------------------------------*/
/*********************************************************************************************************************/
    scr_uart_config();
    scr_enable_int();

    while(1)
    {
        scr_uart_receive(rxmBuffer, Message_Size);
        scr_uart_transmit(rxmBuffer, Message_Size);
    }
}

