#define UART_BAUDRATE           115200
/* UART receive and transmit port pin */

#define UART_PIN_RX1             IfxAsclin1_RXB_P15_5_IN    /*UART1*/
#define UART_PIN_TX1             IfxAsclin1_TX_P15_4_OUT

#define UART_RX_BUFFER_SIZE     64                                      /* Definition of the receive buffer size    */
#define UART_TX_BUFFER_SIZE     64                                      /* Definition of the transmit buffer size   */
/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
/* Declaration of the ASC handle */

static IfxAsclin_Asc g_asc1Handle;

static uint8 g_Tx1Buffer[UART_TX_BUFFER_SIZE + sizeof(Ifx_Fifo) + 8];
static uint8 g_Rx1Buffer[UART_RX_BUFFER_SIZE + sizeof(Ifx_Fifo) + 8];

/*********************************************************************************************************************/
/*--------------------------------------------Private Variables/Constants--------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/

/* Interrupt function */

IFX_INTERRUPT(asclin1TxISR, 0, 21);
void asclin1TxISR(void)
{
    IfxAsclin_Asc_isrTransmit(&g_asc1Handle);
}

IFX_INTERRUPT(asclin1RxISR, 0, 20);
void asclin1RxISR(void)
{
    IfxAsclin_Asc_isrReceive(&g_asc1Handle);
}

void init_ASCLIN1(void)
{
    IfxAsclin_Asc_Config ascConfig1;
    IfxAsclin_Asc_initModuleConfig(&ascConfig1, &MODULE_ASCLIN1);

    ascConfig1.baudrate.baudrate     = UART_BAUDRATE;                                       /* default baudrate (the fractional dividier setup will be calculated in initModule*/

   /* Default Values for Bit Timings */
    ascConfig1.bitTiming.medianFilter        = IfxAsclin_SamplesPerBit_one;                 /* one sample per bit*/
    ascConfig1.bitTiming.samplePointPosition = IfxAsclin_SamplePointPosition_3;             /* sample point position at 3*/
   /* Default Values for Frame Control */
    ascConfig1.frame.shiftDir                = IfxAsclin_ShiftDirection_lsbFirst;           /* shift diection LSB first*/
    ascConfig1.frame.parityBit               = FALSE;                                       /* disable parity*/
    ascConfig1.frame.parityType              = IfxAsclin_ParityType_even;                   /* even parity (if parity enabled)*/
    ascConfig1.frame.dataLength              = IfxAsclin_DataLength_8;                      /* number of bits per transfer 8*/

   /* Default Values for Interrupt Config */
    ascConfig1.interrupt.rxPriority    = 20;                                /* receive interrupt priority 0*/
    ascConfig1.interrupt.txPriority    = 21;                                /* transmit interrupt priority 0*/
    ascConfig1.interrupt.typeOfService = IfxCpu_Irq_getTos(IfxCpu_getCoreIndex());          /* type of service CPU0*/


    /* Pin configuration */
    const IfxAsclin_Asc_Pins pins =
    {
        NULL_PTR,       IfxPort_InputMode_pullUp,       /* CTS pin not used */
        &UART_PIN_RX1,   IfxPort_InputMode_pullUp,      /* RX pin           */
        NULL_PTR,       IfxPort_OutputMode_pushPull,    /* RTS pin not used */
        &UART_PIN_TX1,   IfxPort_OutputMode_pushPull,   /* TX pin           */
        IfxPort_PadDriver_cmosAutomotiveSpeed1
    };

   /* init pointers */
    ascConfig1.pins           = &pins;                                 /* pins to null pointer*/

    ascConfig1.rxBuffer       = &g_Rx1Buffer;                           /* Rx Fifo buffer*/
    ascConfig1.txBuffer       = &g_Tx1Buffer;                           /* Tx Fifo buffer*/
    ascConfig1.txBufferSize   = UART_RX_BUFFER_SIZE;                    /* Rx Fifo buffer size*/
    ascConfig1.rxBufferSize   = UART_TX_BUFFER_SIZE;                    /* Rx Fifo buffer size*/

    IfxAsclin_Asc_initModule(&g_asc1Handle, &ascConfig1); /* Initialize module with above parameters */
}

void send_UART_message(void)
{
    const char* messages = "HELLO_SCR";
    Ifx_SizeT message_len = strlen(messages);
    IfxAsclin_Asc_write(&g_asc1Handle, messages, &message_len, TIME_INFINITE);
}
