/*  TC4_Spectrum_Example.h                                                                                           */
/*  Header for Spectrum Analyzer example                                                                             */
/*                                                                                                                   */
/*  Multi-core spectrum analyzer:                                                                                    */
/*  - CPU0: TFT initialization and rendering                                                                         */
/*  - CPU1: Signal generation and FFT computation                                                                    */
/*********************************************************************************************************************/

#ifndef TC4_SPECTRUM_EXAMPLE_H
#define TC4_SPECTRUM_EXAMPLE_H

#include "Ifx_Types.h"

/*----------------------------------FFT Parameters----------------------------*/
#define FFT_SIZE        512     /* FFT length (must be power of 2) */
#define FFT_BITS        9       /* log2(FFT_SIZE) */
#define SAMPLE_RATE     44100.0f /* Simulated sample rate in Hz */

/*----------------------------------Spectrum Parameters-----------------------*/
#define NUM_BANDS       256     /* Number of frequency bands (FFT_SIZE/2) */
#define BAND_WIDTH      1       /* Width of each bar in pixels */
#define BAND_GAP        0       /* No gap - continuous spectrum look */
#define SEGMENT_HEIGHT  4       /* Height of each LED segment */
#define SEGMENT_GAP     1       /* Gap between segments */
#define NUM_SEGMENTS    44      /* Number of segments per bar */
#define START_X         32      /* Left margin (centered) */
#define START_Y         230     /* Bottom of display area */


/*----------------------------------CPU0 Functions (Rendering)----------------*/

/* Initialize the spectrum analyzer display                                                                          */
/* Returns 0 on success                                                                                              */
/* Call from CPU0 during startup. Initializes TFT and clears buffers.                                                */
sint32 spectrum_example_setup(void);

/* Render the spectrum display                                                                                       */
/* Call from CPU0 main loop or timer interrupt.                                                                      */
/* Reads bandValues[] updated by CPU1 and renders spectrum bars.                                                     */
void spectrum_example_refresh(void);

/*----------------------------------CPU1 Functions (Signal Processing)--------*/

/* Generate mock audio signal                                                                                        */
/* Call from CPU1. Generates a composite signal with multiple                                                        */
/* frequency components and fills the FFT input buffer.                                                              */
void spectrum_generate_signal(void);

/* Compute FFT and update spectrum data                                                                              */
/* Call from CPU1 after spectrum_generate_signal().                                                                  */
/* Computes 256-point FFT and updates bandValues[] for rendering.                                                    */
/* Sets spectrumDataReady flag when complete.                                                                        */
void spectrum_compute_fft(void);


#endif /* TC4_SPECTRUM_EXAMPLE_H */
