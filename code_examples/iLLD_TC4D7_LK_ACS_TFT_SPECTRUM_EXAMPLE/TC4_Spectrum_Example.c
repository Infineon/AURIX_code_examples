#define PI_F            3.14159265358979f
#define TWO_PI_F        6.28318530717959f

/*----------------------------------Global Variables--------------------------*/
/* TFT display - CPU0 only */
TFT_LCD tft;

/* Display state arrays - CPU0 only (sint8 sufficient: values 0 to NUM_SEGMENTS) */
