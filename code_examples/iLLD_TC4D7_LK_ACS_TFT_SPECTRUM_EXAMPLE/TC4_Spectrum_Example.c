/*----------------------------------Main Entry Point--------------------------*/

/* Initialize spectrum analyzer (called by CPU0)                                                                     */
/* Sets up the TFT display and initializes all data arrays.                                                          */
sint32 spectrum_example_setup(void)
{
    uint16 identifier;
    sint32 i;
    
    /* Initialize timing system */
    initTime();
    
    /* Initialize TFT LCD */
    TFTLCD_init(&tft);

    /* Read TFT LCD ID and initialize */
    identifier = TFTLCD_readID(&tft);
    if (identifier == 0 || identifier == 0xFFFF || identifier == 0x0101)
    {
        identifier = 0x9341;  /* Default to ILI9341 */
    }
    
    TFTLCD_begin(&tft, identifier);
    TFTLCD_setRotation(&tft, 1);  /* Landscape mode */
    
    /* Clear screen */
    TFTLCD_fillScreen(&tft.gfx, BLACK);
    
    /* Draw static UI elements */
    drawStaticUI();
    
    /* Initialize arrays */
    for (i = 0; i < NUM_BANDS; i++)
    {
        bandValues[i] = 0;
        oldBarHeights[i] = 0;
        peakHold[i] = 0;
        peakTimer[i] = 0;
    }
    
    /* Initialize FFT buffers */
    for (i = 0; i < FFT_SIZE; i++)
    {
        fftInput[i].real = 0.0f;
        fftInput[i].imag = 0.0f;
        fftOutput[i].real = 0.0f;
        fftOutput[i].imag = 0.0f;
    }
    
    /* Initialize signal generation state */
    signalTime = 0.0f;
    randomSeed = 12345;
    
    /* Clear synchronization flag */
    spectrumDataReady = 0;
    
    /* Memory barrier to ensure all initialization is visible to other CPUs */
    __dsync();
    
    return 0;
}

