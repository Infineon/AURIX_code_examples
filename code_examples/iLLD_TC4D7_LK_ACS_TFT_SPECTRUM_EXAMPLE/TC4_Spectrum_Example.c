/* Synchronization flag: set by CPU1 when new data ready, cleared by CPU0 after render */
uint32 spectrumDataReady;
/*----------------------------------Helper Functions--------------------------*/

/* Integer to string conversion */
static void intToStr(sint32 value, char *str)
{
    sint32 i = 0;
    sint32 negative = 0;
    char temp[16];
    
    if (value < 0)
    {
        negative = 1;
        value = -value;
    }
    
    if (value == 0)
    {
        str[0] = '0';
        str[1] = '\0';
        return;
    }
    
    while (value > 0)
    {
        temp[i++] = '0' + (value % 10);
        value /= 10;
    }
    
    sint32 j = 0;
    if (negative)
    {
        str[j++] = '-';
    }
    while (i > 0)
    {
        str[j++] = temp[--i];
    }
    str[j] = '\0';
}

/* Simple random number generator (returns float32 0.0 to 1.0) */
static float32 randomFloat(void)
{
    randomSeed = randomSeed * 1103515245 + 12345;
    return (float32)((randomSeed >> 16) & 0x7FFF) / 32768.0f;
}

/* Power function approximation */
static float32 powApprox(float32 base, float32 exp)
{
    float32 result = 1.0f;
    sint32 intExp = (sint32)exp;
    float32 frac;
    sint32 i;
    
    for (i = 0; i < intExp; i++)
    {
        result *= base;
    }
    frac = exp - (float32)intExp;
    if (frac > 0)
    {
        result *= (1.0f + frac * (base - 1.0f));
    }
    return result;
}

/*----------------------------------Signal Generation (CPU1)------------------*/

/* Generate a mock audio signal with multiple frequency components                                                   */
/*                                                                                                                   */
/* This function creates a composite signal containing:                                                              */
/* - A base frequency (440 Hz - A4 note)                                                                             */
/* - Harmonics at 880 Hz, 1320 Hz                                                                                    */
/* - A sweeping frequency component                                                                                  */
/* - Random noise for realism                                                                                        */
/*                                                                                                                   */
/* Called by CPU1 to fill the FFT input buffer.                                                                      */
void spectrum_generate_signal(void)
{
    float32 dt;
    float32 slowPhase;
    float32 medPhase;
    float32 kickEnv;
    float32 snareEnv;
    float32 hihatEnv;
    float32 sweep1;
    float32 sweep2;
    float32 wobble;
    float32 bassNote;
    sint32 noteSelect;
    sint32 i;
    float32 t;
    float32 sample;
    float32 kickFreq;
    float32 bassAmp;
    float32 wobbleAmp;
    float32 hihatNoise;
    float32 padAmp;
    float32 arpTime;
    float32 arpFreq;
    float32 arpEnv;
    
    dt = 1.0f / SAMPLE_RATE;
    
    /* Time-varying parameters for animation */
    slowPhase = sinf(signalTime * 0.3f);           /* Slow evolution */
    medPhase = sinf(signalTime * 1.2f);            /* Medium rhythm */
    
    /* Simulated kick drum pattern (4 on the floor) */
    kickEnv = powApprox(0.5f + 0.5f * sinf(signalTime * 8.0f), 4.0f);
    
    /* Snare/clap pattern (off-beats) */
    snareEnv = powApprox(0.5f + 0.5f * sinf(signalTime * 8.0f + PI_F), 6.0f);
    
    /* Hi-hat pattern (fast) */
    hihatEnv = 0.3f + 0.7f * powApprox(0.5f + 0.5f * sinf(signalTime * 16.0f), 2.0f);
    
    /* Sweeping synth frequencies */
    sweep1 = 300.0f + 700.0f * (0.5f + 0.5f * sinf(signalTime * 0.7f));
    sweep2 = 1500.0f + 2500.0f * (0.5f + 0.5f * sinf(signalTime * 0.4f + 1.0f));
    wobble = 100.0f + 400.0f * (0.5f + 0.5f * sinf(signalTime * 3.0f));  /* Dubstep wobble */
    
    /* Bass note that changes */
    bassNote = 55.0f;  /* A1 */
    noteSelect = ((sint32)(signalTime * 0.5f)) % 4;
    if (noteSelect == 1)
    {
        bassNote = 65.4f;       /* C2 */
    }
    else if (noteSelect == 2)
    {
        bassNote = 73.4f;  /* D2 */
    }
    else if (noteSelect == 3)
    {
        bassNote = 82.4f;  /* E2 */
    }
    
    for (i = 0; i < FFT_SIZE; i++)
    {
        t = signalTime + (float32)i * dt;
        sample = 0.0f;
        
        /*--- Kick drum: punchy low frequency burst ---*/
        kickFreq = 60.0f - 20.0f * kickEnv;  /* Pitch drops as kick decays */
        sample += 0.2f * kickEnv * sinf(TWO_PI_F * kickFreq * t);
        
        /*--- Sub-bass: follows the kick ---*/
        sample += 0.12f * kickEnv * sinf(TWO_PI_F * 40.0f * t);
        
        /*--- Bass synth: sustained note with harmonics ---*/
        bassAmp = 0.15f * (0.6f + 0.4f * medPhase);
        sample += bassAmp * sinf(TWO_PI_F * bassNote * t);
        sample += bassAmp * 0.5f * sinf(TWO_PI_F * bassNote * 2.0f * t);  /* Octave */
        sample += bassAmp * 0.3f * sinf(TWO_PI_F * bassNote * 3.0f * t);  /* Fifth */
        
        /*--- Wobble bass (dubstep style) ---*/
        wobbleAmp = 0.1f * (0.5f + 0.5f * sinf(signalTime * 6.0f));
        sample += wobbleAmp * sinf(TWO_PI_F * wobble * t);
        
        /*--- Snare: white noise burst + tone ---*/
        sample += 0.08f * snareEnv * (randomFloat() * 2.0f - 1.0f);
        sample += 0.05f * snareEnv * sinf(TWO_PI_F * 200.0f * t);
        
        /*--- Hi-hats: high frequency noise ---*/
        hihatNoise = randomFloat() * 2.0f - 1.0f;
        sample += 0.04f * hihatEnv * hihatNoise * sinf(TWO_PI_F * 8000.0f * t);
        sample += 0.03f * hihatEnv * sinf(TWO_PI_F * 10000.0f * t);
        
        /*--- Sweeping synth pad ---*/
        padAmp = 0.08f * (0.5f + 0.5f * slowPhase);
        sample += padAmp * sinf(TWO_PI_F * sweep1 * t);
        sample += padAmp * 0.7f * sinf(TWO_PI_F * sweep1 * 1.5f * t);  /* Fifth above */
        sample += padAmp * 0.5f * sinf(TWO_PI_F * sweep2 * t);
        
        /*--- Arpeggiated synth: cycling through notes ---*/
        arpTime = fmodf(signalTime * 8.0f, 4.0f);
        if (arpTime < 1.0f)
        {
            arpFreq = 523.0f;       /* C5 */
        }
        else if (arpTime < 2.0f)
        {
            arpFreq = 659.0f;  /* E5 */
        }
        else if (arpTime < 3.0f)
        {
            arpFreq = 784.0f;  /* G5 */
        }
        else
        {
            arpFreq = 1047.0f;                      /* C6 */
        }
        
        arpEnv = 1.0f - fmodf(arpTime, 1.0f);  /* Decay envelope */
        arpEnv = arpEnv * arpEnv;
        sample += 0.06f * arpEnv * sinf(TWO_PI_F * arpFreq * t);
        sample += 0.03f * arpEnv * sinf(TWO_PI_F * arpFreq * 2.0f * t);
        
        /*--- Occasional high frequency sparkles ---*/
        if (randomFloat() > 0.997f)
        {
            sample += 0.15f * sinf(TWO_PI_F * (5000.0f + randomFloat() * 10000.0f) * t);
        }
        
        /*--- Ambient pad in background ---*/
        sample += 0.02f * sinf(TWO_PI_F * 3500.0f * t) * (0.5f + 0.5f * sinf(signalTime * 0.8f));
        sample += 0.02f * sinf(TWO_PI_F * 7000.0f * t) * (0.5f + 0.5f * sinf(signalTime * 1.1f));
        
        /* Store as complex number */
        fftInput[i].real = sample;
        fftInput[i].imag = 0.0f;
    }
    
    /* Advance time for animation */
    signalTime += (float32)FFT_SIZE * dt;
    if (signalTime > 1000.0f)
    {
        signalTime = 0.0f;  /* Prevent overflow */
    }
}

/* Compute FFT and convert to spectrum magnitude                                                                    */
/*                                                                                                                   */
/* This function:                                                                                                    */
/* 1. Applies a Hanning window to reduce spectral leakage                                                            */
/* 2. Computes the FFT using the iLLD library                                                                        */
/* 3. Calculates magnitude for each frequency bin                                                                    */
/* 4. Scales and maps to bandValues for display                                                                      */
/*                                                                                                                   */
/* Called by CPU1 after signal generation.                                                                           */
void spectrum_compute_fft(void)
{
    sint32 i;
    float32 window;
    float32 real;
    float32 imag;
    float32 magnitude;
    float32 db;
    float32 scaled;
    float32 freqBalance;
    
    /* Apply Hanning window to reduce spectral leakage */
    for (i = 0; i < FFT_SIZE; i++)
    {
        window = 0.5f * (1.0f - cosf(TWO_PI_F * (float32)i / (float32)(FFT_SIZE - 1)));
        fftInput[i].real *= window;
        /* imag stays 0 */
    }
    
    /* Compute FFT using iLLD library */
    Ifx_FftF32_radix2(fftOutput, fftInput, FFT_SIZE);
    
    /* Convert FFT output to magnitude spectrum */
    for (i = 0; i < NUM_BANDS; i++)
    {
        /* Calculate magnitude: sqrt(real^2 + imag^2) */
        real = fftOutput[i].real;
        imag = fftOutput[i].imag;
        magnitude = sqrtf(real * real + imag * imag);
        
        /* Normalize magnitude by FFT size */
        magnitude = magnitude / (float32)FFT_SIZE;
        
        /* Convert to dB scale */
        if (magnitude > 0.00001f)
        {
            db = 20.0f * log10f(magnitude);
        }
        else
        {
            db = -100.0f;
        }
        
        /* Map dB range to display range (0-400 for compatibility with display code) */
        /* Use wider range: -80dB to -10dB, gives more headroom */
        scaled = (db + 80.0f) * (400.0f / 70.0f);
        
        /* Apply frequency-dependent scaling to balance the spectrum */
        /* Low frequencies need attenuation, high frequencies need boost */
        
        if (i < 5)
        {
            /* Very low frequencies - attenuate more */
            freqBalance = 0.5f + (float32)i * 0.1f;
        }
        else if (i < 30)
        {
            /* Low-mid frequencies - slight attenuation */
            freqBalance = 1.0f;
        }
        else if (i < 80)
        {
            /* Mid frequencies - neutral */
            freqBalance = 1.0f + (float32)(i - 30) * 0.005f;
        }
        else
        {
            /* High frequencies - boost */
            freqBalance = 1.25f + (float32)(i - 80) * 0.01f;
        }
        scaled *= freqBalance;
        
        /* Clamp to valid range */
        if (scaled < 0.0f)
        {
            scaled = 0.0f;
        }
        if (scaled > 400.0f)
        {
            scaled = 400.0f;
        }
        
        bandValues[i] = (sint16)scaled;
    }
    
    /* Memory barrier to ensure all writes are visible to other CPUs */
    __dsync();
    
    /* Signal that new data is ready for CPU0 to render */
    spectrumDataReady = 1;
    
    /* Another barrier to ensure the flag write is visible */
    __dsync();
}

/*----------------------------------Spectrum Display Functions----------------*/

/* Get color for a segment based on its position (height percentage) */
static uint16 getSegmentColor(sint32 segment, sint32 totalSegments)
{
    float32 ratio = (float32)segment / (float32)totalSegments;
    sint32 g;
    float32 t;
    
    if (ratio < 0.5f)
    {
        /* Green to Yellow gradient */
        sint32 r = (sint32)(ratio * 2.0f * 31.0f);
        return (r << 11) | 0x07E0;  /* Mix red into green */
    }
    else if (ratio < 0.75f)
    {
        /* Yellow to Orange */
        t = (ratio - 0.5f) * 4.0f;
        g = (sint32)(63.0f - t * 31.0f);
        return 0xF800 | (g << 5);  /* Red with decreasing green */
    }
    else
    {
        /* Orange to Red */
        t = (ratio - 0.75f) * 4.0f;
        g = (sint32)(32.0f - t * 32.0f);
        if (g < 0)
        {
            g = 0;
        }
        return 0xF800 | (g << 5);
    }
}

/* Display peak frequency in top right corner */
static void displayPeakFrequency(void)
{
    /* Find the band with highest value */
    sint32 peakBand = 0;
    sint32 peakValue = 0;
    sint32 i;
    float32 logFreq;
    sint32 freq;
    
    for (i = 0; i < NUM_BANDS; i++)
    {
        if (bandValues[i] > peakValue)
        {
            peakValue = bandValues[i];
            peakBand = i;
        }
    }
    
    /* Calculate frequency (logarithmic scale from 20Hz to 20kHz) */
    logFreq = 20.0f * powApprox(10.0f, (float32)peakBand / (float32)NUM_BANDS * 3.0f);
    freq = (sint32)logFreq;
    
    /* Clear previous value area */
    GFX_fillRect(&tft.gfx, 270, 6, 46, 12, BLACK);
    
    /* Display frequency value */
    GFX_setTextSize(&tft.gfx, 1);
    GFX_setTextColor(&tft.gfx, YELLOW);
    GFX_setCursor(&tft.gfx, 271, 8);
    
    if (freq < 1000)
    {
        intToStr(freq, strBuf);
        GFX_print(&tft.gfx, strBuf);
        GFX_print(&tft.gfx, "Hz");
    }
    else
    {
        intToStr(freq / 1000, strBuf);
        GFX_print(&tft.gfx, strBuf);
        GFX_print(&tft.gfx, ".");
        intToStr((freq % 1000) / 100, strBuf);
        GFX_print(&tft.gfx, strBuf);
        GFX_print(&tft.gfx, "k");
    }
}

/* Draw segmented spectrum bars */
static void drawSpectrum(void)
{
    sint32 band;
    sint32 xPos;
    sint32 numLit;
    sint32 oldLit;
    sint32 seg;
    sint32 yPos;
    sint32 peakY;
    uint16 color;
    
    for (band = 0; band < NUM_BANDS; band++)
    {
        xPos = START_X + band * (BAND_WIDTH + BAND_GAP);
        
        /* Scale value to number of segments */
        numLit = (bandValues[band] * NUM_SEGMENTS) / 400;
        if (numLit < 0)
        {
            numLit = 0;
        }
        if (numLit > NUM_SEGMENTS)
        {
            numLit = NUM_SEGMENTS;
        }
        
        oldLit = oldBarHeights[band];
        
        /* Draw/erase only changed segments for speed */
        if (numLit > oldLit)
        {
            /* Draw new segments */
            for (seg = oldLit; seg < numLit; seg++)
            {
                yPos = START_Y - seg * (SEGMENT_HEIGHT + SEGMENT_GAP);
                color = getSegmentColor(seg, NUM_SEGMENTS);
                GFX_fillRect(&tft.gfx, xPos, yPos - SEGMENT_HEIGHT, BAND_WIDTH, SEGMENT_HEIGHT, color);
            }
        }
        else if (numLit < oldLit)
        {
            /* Erase old segments */
            for (seg = numLit; seg < oldLit; seg++)
            {
                yPos = START_Y - seg * (SEGMENT_HEIGHT + SEGMENT_GAP);
                GFX_fillRect(&tft.gfx, xPos, yPos - SEGMENT_HEIGHT, BAND_WIDTH, SEGMENT_HEIGHT, BLACK);
            }
        }
        
        /* Peak indicator with hold and decay */
        if (numLit > peakHold[band])
        {
            peakHold[band] = (sint8)numLit;
            peakTimer[band] = 20;
        }
        
        /* Draw peak indicator */
        if (peakHold[band] > 0)
        {
            peakY = START_Y - peakHold[band] * (SEGMENT_HEIGHT + SEGMENT_GAP);
            GFX_fillRect(&tft.gfx, xPos, peakY - SEGMENT_HEIGHT, BAND_WIDTH, SEGMENT_HEIGHT - 1, WHITE);
            
            if (peakTimer[band] > 0)
            {
                peakTimer[band]--;
            }
            else
            {
                /* Erase old peak and decay */
                GFX_fillRect(&tft.gfx, xPos, peakY - SEGMENT_HEIGHT, BAND_WIDTH, SEGMENT_HEIGHT, BLACK);
                peakHold[band]--;
            }
        }
        
        oldBarHeights[band] = (sint8)numLit;
    }
}

