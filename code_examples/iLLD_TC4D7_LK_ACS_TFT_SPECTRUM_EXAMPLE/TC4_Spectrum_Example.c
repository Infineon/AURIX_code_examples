/*  TC4_Spectrum_Example.c                                                                                           */
/*  Spectrum Analyzer example for TC4D with TFT LCD                                                                  */
/*                                                                                                                   */
/*  This example demonstrates a 128-band spectrum analyzer display                                                   */
/*  using FFT computation on CPU1 and rendering on CPU0.                                                             */
/*                                                                                                                   */
/*  Features:                                                                                                        */
/*  - Mock signal generation with multiple frequency components                                                      */
/*  - 256-point FFT computed on CPU1 using Ifx_FftF32                                                                */
/*  - 128 frequency bands with segmented LED-style bars                                                              */
/*  - Color gradient from green to red based on amplitude                                                            */
/*  - Peak hold indicators with decay                                                                                */
/*                                                                                                                   */
/*  Architecture:                                                                                                    */
/*  - CPU0: TFT initialization and spectrum rendering                                                                */
/*  - CPU1: Signal generation and FFT computation                                                                    */
/*********************************************************************************************************************/

