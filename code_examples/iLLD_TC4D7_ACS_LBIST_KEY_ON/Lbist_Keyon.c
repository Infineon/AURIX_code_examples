#include "IfxTriLbist.h"
#include "IfxTri_reg.h"
#include "Ifx_Types.h"
#include "IfxSmmRst.h"
#include "IfxSmm_regdef.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define MAX_FAIL_COUNT                  3                        /* Maximum number of LBIST runs allowed */

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
IfxSmmRst_Reset g_resetStatus;  /* Stores information of the triggered reset */

/*********************************************************************************************************************/
/*--------------------------------------------structure--------------------------------------------*/
/*********************************************************************************************************************/
/* Expected Safety LBIST Signature (MISR) for the TC4Dx device */
typedef union{
    struct{
        uint16 dom0Failed:1;
        uint16 dom1Failed:1;
        uint16 dom2Failed:1;
        uint16 dom3Failed:1;
        uint16 dom4Failed:1;
        uint16 dom5Failed:1;
        uint16 dom6Failed:1;
        uint16 dom7Failed:1;

        uint16 notDone:1;
        uint16 notTerminatedProperlyLBTERM:1; /* LBIST was not properly terminated for respective domains */
        uint16 earlyTerminatedPORST:1; /* LBIST termination due to warm PORST */
        uint16 unused:5;
    };
    uint16 lbistKeyonStatus;
} LbistkeyonStatus;

typedef struct
{
    boolean oneEyeLed0LbistPassed;
    boolean oneEyeLed1LbistPassedFirstRun;
    boolean oneEyeLed2LbistPassedMoreRun;
    boolean oneEyeLed3WrongLbist;
    boolean oneEyeLed4LbistNotExecuted;
    boolean oneEyeLed5DeviceDefect;

    uint8   failCounter;
} LbistExecutionStatus;

LbistExecutionStatus g_LbistExecutionStatus;

LbistkeyonStatus g_LbistKeyonStatus;

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/
uint8 getSafetyIndication(void);
uint8 getSessionIndication(void);
void resetLbistExecutionStatus(void);
void retriggerLbistKeyon(void);
void handleLbistKeyonCompleted(void);

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
/*
 * Safety-only test (only safety-relevant logic tested) for key-on
 * */
uint8 getSafetyIndication(void)
{
    uint8 safetyIndication;
    safetyIndication    = MODULE_TRI.LBIST.STAT.TEST.B.SAFEIND;
    return safetyIndication;
}

/*
 * LBIST was triggered by a pending key-off request — results belong to a key-off run, not key-on
 * */
uint8 getSessionIndication(void)
{
    uint8 sessionIndication;
    sessionIndication    = MODULE_TRI.LBIST.STAT.TEST.B.KEYIND;
    return sessionIndication;
}

/*
 * Resets all LBIST status LEDs and fail counter to their default state
 * */
void resetLbistExecutionStatus(void)
{
    /* reset the OneEye GUI LEDs */
    g_LbistExecutionStatus.oneEyeLed0LbistPassed = FALSE;
    g_LbistExecutionStatus.oneEyeLed1LbistPassedFirstRun = FALSE;
    g_LbistExecutionStatus.oneEyeLed2LbistPassedMoreRun = FALSE;
    g_LbistExecutionStatus.oneEyeLed5DeviceDefect = FALSE;
    g_LbistExecutionStatus.oneEyeLed4LbistNotExecuted = FALSE;
    g_LbistExecutionStatus.oneEyeLed3WrongLbist = FALSE;

    /* initial counter counter */
    g_LbistExecutionStatus.failCounter = 0;
}

/*
 * Clears reset status registers and re-triggers an LBIST key-on run
 * */
void retriggerLbistKeyon(void)
{
    /* Clear reset status registers */
    IfxSmmRst_clearAllResetRegisters();

    /* trigger LBIST safety test */
    IfxTriLbist_triggerInline(&IfxTriLbist_keyOnDefaultConfig);
}

/*
 * Evaluates the LBIST key-on result
 * */
void handleLbistKeyonCompleted(void)
{
    uint8 safetyIndicator = 0;
    uint8 sessionIndicator = 0;

    /* reset LEDs and fail counter */
    resetLbistExecutionStatus();

    /* Check if the last reset was a Cold Power On Reset */
    if (g_resetStatus.resetStatus.B.CLDPORST == 1)
    {
        /*
         * No external PORST interrupted LBIST and
         * LBIST terminated properly and
         * LBIST done global and each domain
         * verify the signature values for each domain
         * */
        g_LbistKeyonStatus.lbistKeyonStatus = IfxTriLbist_evaluateResult(
                &IfxTriLbist_keyOnDefaultConfig.signature[0]);
        /*
         * check if Lbist key-on successfully executed
         * */
        if (IFXTRILBIST_SUCCESS == g_LbistKeyonStatus.lbistKeyonStatus)
        {
            /* get safety indication */
            safetyIndicator = getSafetyIndication();

            /* get session indication whether key-on or key-off run */
            sessionIndicator = getSessionIndication();

            /* get the fail count */
            g_LbistExecutionStatus.failCounter = IfxTriLbist_getFailCount();

            /* This function clears LBIST Status registers and brings LBIST module to its default state */
            IfxTriLbist_resetLbist();
            /*
             * Safety-logic-only LBIST executed and
             * Confirms this was a key-on (not key-off) run
             * */
            if ((IfxTriLbist_keyOnDefaultConfig.safetySelEnable == safetyIndicator) &&
                (IfxTriLbist_keyOnDefaultConfig.keyoffEnable == sessionIndicator))
            {
                /* OneEye LED will be on */
                g_LbistExecutionStatus.oneEyeLed0LbistPassed = TRUE;

                /* if LBIST is done in first attempt */
                if (0 == g_LbistExecutionStatus.failCounter)
                {
                    g_LbistExecutionStatus.oneEyeLed1LbistPassedFirstRun = TRUE;
                }

                /* if LBIST is done in more than one attempt */
                else
                {
                    /* if LBIST is done in more than one attempt */
                    g_LbistExecutionStatus.oneEyeLed2LbistPassedMoreRun = TRUE;
                }
            }

            /* Wrong LBIST is executed */
            else
            {
                g_LbistExecutionStatus.oneEyeLed3WrongLbist = TRUE;
            }
        }

        /* LBIST Key-on not executed i.e. coming from cold PORST and LBIST is not trigger by FW */
        else if ((IFXTRILBIST_NOT_TERMINATED == g_LbistKeyonStatus.lbistKeyonStatus) &&
                 (FALSE == IfxTriLbist_isDone()))
        {
            /*  not executed LED in OneEye will be on */
            g_LbistExecutionStatus.oneEyeLed4LbistNotExecuted = TRUE;
        }

        /* LBIST Key-on is executed but failed*/
        else
        {
            /* get fail counter */
            g_LbistExecutionStatus.failCounter = IfxTriLbist_getFailCount();

            /* Repeat at least 2 times → Maximum 3 consecutive runs total */
            if (g_LbistExecutionStatus.failCounter < MAX_FAIL_COUNT)
            {
                /* increment LBIST fail count */
                IfxTriLbist_incrementFailCount();

                /* This function clears LBIST Status registers and brings LBIST module to its default state */
                IfxTriLbist_resetLbist();

                /* trigger the LBIST key-on*/
                retriggerLbistKeyon();
            }

            /* Maximum attempt finished, device defective */
            else
            {
                g_LbistExecutionStatus.oneEyeLed5DeviceDefect = TRUE;
            }
        }
    }

    /* not coming from cold PORST, therefore, no LBIST trigger */
    else
    {
        /* OneEye not executed LED will be on */
        g_LbistExecutionStatus.oneEyeLed4LbistNotExecuted = TRUE;
    }
}

/*
 * Coordinates the LBIST key-on check: captures reset status, evaluates the result, then clears reset registers
 * */
void processLbistKeyOn(void)
{
    /* Get the last Reset status */
    IfxSmmRst_evaluateReset(&g_resetStatus);

    /* Evaluate LBIST key on */
    handleLbistKeyonCompleted();

    /* Clear reset status registers */
    IfxSmmRst_clearAllResetRegisters();
}
