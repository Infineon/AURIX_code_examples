#ifndef PPU_AUX_H
#define PPU_AUX_H 1

#include "Ifx_Types.h"

/* ARC auxiliary register addresses used by this firmware. */
#define PPU_AUX_TIMER0_COUNT      0x21
#define PPU_AUX_TIMER0_CONTROL    0x22
#define PPU_AUX_TIMER0_LIMIT      0x23

#define PPU_AUX_ERET              0x400   /* exception return address           */
#define PPU_AUX_ERSTATUS          0x402   /* status snapshot at the exception   */
#define PPU_AUX_ECR               0x403   /* [23:16] vector, [15:8] cause, [7:0] param */
#define PPU_AUX_EFA               0x404   /* faulting address                   */
#define PPU_AUX_MPU_EN            0x409   /* MPU enable                         */

#if defined(__arc__)

/** Write \p val to the auxiliary register \p reg (compile-time constant). */
#define PPU_AUX_STORE(val, reg)                                               \
    __asm__ volatile ("sr %0, [%1]"                                           \
                      :                                                       \
                      : "r" ((uint32)(val)), "i" (reg)                        \
                      : "memory")

/** Read the auxiliary register \p reg (compile-time constant). */
#define PPU_AUX_LOAD(reg)                                                     \
    __extension__ ({                                                          \
        uint32 ppu_aux_val_;                                                  \
        __asm__ volatile ("lr %0, [%1]"                                       \
                          : "=r" (ppu_aux_val_)                               \
                          : "i" (reg));                                       \
        ppu_aux_val_;                                                         \
    })

#else /* host / syntax-check builds */

#define PPU_AUX_STORE(val, reg)   do { (void)(val); } while (0)
#define PPU_AUX_LOAD(reg)         ((uint32)0)

#endif /* __arc__ */

#endif /* PPU_AUX_H */
