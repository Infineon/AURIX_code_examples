/*
 * Inference IPC payload shared between TriCore CPU0 and the PPU (ARC EV) core.
 * Completes the forward-declared TcPpuIpcData struct from SharedData.h.
 *
 * The storage lives in the non-cached PPU LMU region (linker section .shared_bss_ppu_tc)
 * and is allocated by the PPU image; the TriCore reaches it through
 * ppuInterfaceData.ppuIpcDataPtr. Both images compile this header (and model.h), so the
 * layout is guaranteed identical on both sides.
 */

#ifndef PPU_IPC_H
#define PPU_IPC_H

#include "Ifx_Types.h"
#include "app_config.h"   /* APP_MODEL_MAX_* / APP_PPU_MAX_REGIONS bounds (user-tunable) */

/* Upper bounds for the shared I/O buffers, in BYTES. Kept model-agnostic (not
 * tied to the generated IMAI_* macro names); the actual byte counts come from
 * the model metadata at run time. Tune via app_config.h. */
#define PPU_IPC_MAX_INPUT_BYTES     APP_MODEL_MAX_INPUT_BYTES
#define PPU_IPC_MAX_OUTPUT_BYTES    APP_MODEL_MAX_OUTPUT_BYTES

/* Every tensor starts on this boundary inside input[]/output[]. A model may mix
 * element widths, and a tight prefix sum would leave e.g. an int32 tensor that
 * follows a 5-byte int8 tensor at an odd address - the PPU hands those offsets
 * straight to IMAI_compute() as typed pointers, so a misaligned one faults
 * (EV_Maligned). 4 covers every element type supported here. */
#define PPU_TENSOR_ALIGN            4u

/* Upper bound on the number of model profiling regions transferred from the PPU
 * to CPU0. Tune via app_config.h. */
#define PPU_IPC_MAX_REGIONS         APP_PPU_MAX_REGIONS

/* --- Model metadata published by the PPU (runtime metadata handoff) ---------
 * The PPU owns the generated model and fills these in at boot from the model's
 * IMAI_*_META tables. CPU0 reads them to build the streaming-protocol streams
 * and size its I/O buffers WITHOUT compiling or linking any generated model
 * file (no model.h, no arc_vector backend on the TriCore). */
#define PPU_META_MAX_TENSORS         APP_MODEL_MAX_TENSORS
#define PPU_META_MAX_DIMS            8u
#define PPU_META_NAME_LEN           40u

/* --- Fatal PPU fault reporting ---------------------------------------------
 * A fatal exception stops the PPU dead, so the record it leaves behind in
 * fault_kind/fault_* is the only way CPU0 can say more than "timeout". */
#define PPU_FAULT_MSG_LEN            64u
#define PPU_FAULT_KIND_MASK          0xFF000000u  /**< Selects the kind field.     */
#define PPU_FAULT_KIND_CPU_EXCEPTION 0x01000000u  /**< Fatal CPU exception.        */
#define PPU_FAULT_KIND_HAL_FAULT     0x02000000u  /**< HAL fault code in low bits. */
#define PPU_HAL_FAULT_SHUTDOWN       8u           /**< kspeedFaultShutdown.        */

/* ARCv2 ECR vector for a protection violation (ecr bits [23:16]). */
#define PPU_ECR_VECTOR_PROTV         0x06u
/* How far below a stack base a fault address still counts as that stack
 * overflowing rather than an unrelated bad access. */
#define PPU_STACK_OVERFLOW_WINDOW    0x10000u

/* One tensor's metadata (mirrors the fields of the model's IMAI_param_def that
 * the streaming protocol needs). Dimension labels are not forwarded; label
 * pointers are passed as NULL on CPU0. */
typedef struct
{
    char    name[PPU_META_NAME_LEN];              /**< Tensor name.                       */
    sint32  type_id;                              /**< IMAGINET_TYPES_* raw value.        */
    float   frequency;                            /**< Sample frequency (Hz).             */
    sint32  rank;                                 /**< Number of dimensions.              */
    sint32  bytes;                                /**< Total tensor size in bytes.        */
    sint32  shift;                                /**< Quantization shift.                */
    float   scale;                                /**< Quantization scale.                */
    sint32  offset;                               /**< Quantization zero-point.           */
    sint32  dim_size[PPU_META_MAX_DIMS];          /**< Per-dimension size.                */
    char    dim_name[PPU_META_MAX_DIMS][PPU_META_NAME_LEN]; /**< Per-dimension name.      */
} PpuTensorMeta;

/* Full model description handed from the PPU to CPU0. */
typedef struct
{
    volatile uint32 ready;                        /**< 1 once the PPU has populated this.  */
    uint32          input_count;
    uint32          output_count;
    uint32          region_count;                 /**< Profiling regions (names below).    */
    PpuTensorMeta   inputs[PPU_META_MAX_TENSORS];
    PpuTensorMeta   outputs[PPU_META_MAX_TENSORS];
    char            region_names[PPU_IPC_MAX_REGIONS][PPU_META_NAME_LEN];
} PpuModelMeta;

/* Simple request/response mailbox for one inference. The flags live in
 * non-cached memory so both cores observe writes without cache maintenance;
 * signalling is via the SRC IPC lines (see PpuInterface.h / TricoreInterface.h).
 *
 * MIMO layout: for a model with N inputs and M outputs, 'input' holds all N
 * input tensors concatenated in metadata order and 'output' holds all M output
 * tensors the same way, each tensor starting on a PPU_TENSOR_ALIGN boundary.
 * Neither side hard-codes per-tensor offsets; both derive them from
 * meta.inputs[]/meta.outputs[].bytes with PpuMeta_inputOffsetBytes() /
 * PpuMeta_outputOffsetBytes() below, so the layout always matches whatever
 * model is linked. The buffers are byte arrays because a model may mix element
 * types; they are aligned so each tensor can be read as its own type. */
struct TcPpuIpcData
{
    volatile uint32 request;                        /**< TC -> PPU: input ready, run inference. */
    volatile uint32 done;                           /**< PPU -> TC: output ready.               */
    volatile uint32 output_valid;                   /**< 0 when the PPU refused to run.         */
    /* Explicitly aligned: tensor 0 sits at offset 0 of each buffer and is read
     * as its own element type, and it keeps 'output' aligned regardless of what
     * APP_MODEL_MAX_INPUT_BYTES is set to. */
    uint8           input[PPU_IPC_MAX_INPUT_BYTES]   __attribute__((aligned(PPU_TENSOR_ALIGN)));
    uint8           output[PPU_IPC_MAX_OUTPUT_BYTES] __attribute__((aligned(PPU_TENSOR_ALIGN)));

    /* PPU-measured region profiling (PPU core cycles), published by the PPU
     * after each inference and read by CPU0 at end of a streaming session.
     * Cumulative across inferences, matching model.c's region counters. */
    volatile uint32 prof_regions;                      /**< Number of valid regions. */
    volatile uint32 prof_visits[PPU_IPC_MAX_REGIONS];  /**< Per-region visit count.  */
    volatile uint64 prof_max[PPU_IPC_MAX_REGIONS];     /**< Per-region max cycles.   */
    volatile uint64 prof_sum[PPU_IPC_MAX_REGIONS];     /**< Per-region summed cycles.*/

    /* Model metadata published once at PPU boot (see PpuModelMeta). Lets CPU0
     * describe the model to the streaming host without linking the model. */
    PpuModelMeta    meta;

    /* Stack bounds, published once at boot. Used by CPU0 to classify a fatal
     * PPU fault: both stacks grow down, so a fault address below stack_base_addr
     * or a vector stack pointer at/below vstack_base_addr is an overflow. */
    volatile uint32 vstack_total_bytes;  /**< Size of the runtime vector stack.      */
    volatile uint32 vstack_base_addr;    /**< _fvstack: bottom of the vector stack.  */
    volatile uint32 stack_base_addr;     /**< _fstack: bottom of the scalar stack.   */
    volatile uint32 stack_top_addr;      /**< _estack: top of the scalar stack.      */

    /* Fatal PPU exception capture. The SPEED HAL routes fatal CPU exceptions to
     * the notification service; the PPU installs one with
     * speed_RegisterNotifyHandlers() and snapshots the state here before the
     * core is stopped (see Ppu_Main.c). Without this a trap is invisible to
     * CPU0 - the PPU just stops answering and the dispatch times out with
     * "done=0 request=0". fault_ready is written last so CPU0 only reads a
     * complete record. */
    volatile uint32 fault_kind;          /**< PPU_FAULT_KIND_*, 0 when none.         */
    volatile uint32 fault_ecr;           /**< Exception Cause Register.              */
    volatile uint32 fault_efa;           /**< Exception Fault Address.               */
    volatile uint32 fault_eret;          /**< Faulting PC (scalar).                  */
    volatile uint32 fault_vec_pc;        /**< VDSP exception PC.                     */
    volatile uint32 fault_vec_sp;        /**< r56 = vector stack pointer at fault.   */
    volatile uint32 fault_payload0;      /**< HAL fault payload (fault callback).    */
    volatile uint32 fault_payload1;      /**< HAL fault payload (fault callback).    */
    char            fault_msg[PPU_FAULT_MSG_LEN]; /**< HAL's message, if any.        */
    volatile uint32 fault_ready;         /**< 1 once the record above is complete.   */
};

/* --- MIMO tensor offset helpers ---------------------------------------------
 * Both cores concatenate tensors in metadata order, each starting on a
 * PPU_TENSOR_ALIGN boundary (see TcPpuIpcData above). These derive each
 * tensor's byte offset within input[]/output[] as an aligned prefix sum over
 * the preceding tensors' sizes, so neither side needs its own copy of the
 * layout math. 'index' is clamped to PPU_META_MAX_TENSORS by the caller
 * (Ppu_publishModelMeta truncates a model with more tensors than that and
 * reports it loudly). */
static inline uint32 PpuMeta_alignUp(uint32 value)
{
    return (value + (PPU_TENSOR_ALIGN - 1u)) & ~(PPU_TENSOR_ALIGN - 1u);
}

static inline uint32 PpuMeta_inputOffsetBytes(const PpuModelMeta *meta, uint32 index)
{
    uint32 offset = 0u;
    uint32 i;
    for (i = 0u; i < index && i < meta->input_count && i < PPU_META_MAX_TENSORS; i++)
    {
        offset = PpuMeta_alignUp(offset + (uint32)meta->inputs[i].bytes);
    }
    return offset;
}

static inline uint32 PpuMeta_outputOffsetBytes(const PpuModelMeta *meta, uint32 index)
{
    uint32 offset = 0u;
    uint32 i;
    for (i = 0u; i < index && i < meta->output_count && i < PPU_META_MAX_TENSORS; i++)
    {
        offset = PpuMeta_alignUp(offset + (uint32)meta->outputs[i].bytes);
    }
    return offset;
}

/* Total bytes spanned by all input / output tensors, including the alignment
 * padding between them. Used to size copies and to check the model fits the
 * mailbox. */
static inline uint32 PpuMeta_totalInputBytes(const PpuModelMeta *meta)
{
    uint32 last = meta->input_count > 0u ? meta->input_count - 1u : 0u;
    return meta->input_count == 0u
         ? 0u
         : PpuMeta_inputOffsetBytes(meta, last) + (uint32)meta->inputs[last].bytes;
}

static inline uint32 PpuMeta_totalOutputBytes(const PpuModelMeta *meta)
{
    uint32 last = meta->output_count > 0u ? meta->output_count - 1u : 0u;
    return meta->output_count == 0u
         ? 0u
         : PpuMeta_outputOffsetBytes(meta, last) + (uint32)meta->outputs[last].bytes;
}

#endif /* PPU_IPC_H */
