/*
 * Shared by both subprojects (TriCore compiles it directly; PPU reaches it via
 * ../../illd_tc4d7_acs_deepcraft_ml_profiler_TC4/PpuShared) - keep exactly one copy so APP_INFER
 * can't silently diverge between the two images.
 *
 * Compile-time application configuration for the DEEPCRAFT streaming firmware.
 * Two independent choices, both resolved at build time:
 *   1. APP_MODE      - stream I/O with a host, or run built-in samples locally as a self-test.
 *   2. APP_TRANSPORT - which link carries the streaming protocol (only used in stream mode).
 * Change the two selection #defines below (or override with -D on the compiler command line)
 * and rebuild. Everything else - which transport is compiled, where printf goes, whether the
 * lwIP stack is pulled in - is derived from these.
 */

#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/* ---- APP_INFER (where the model runs) ----------------------------------- *
 * Independent of APP_MODE / APP_TRANSPORT: selects whether IMAI_compute runs
 * on the TriCore (CPU0) or is offloaded to the PPU (ARC EV) core. The streaming
 * protocol always stays on CPU0; only the inference call is dispatched. */
#define APP_INFER_TRICORE   0   /* IMAI_compute runs on TriCore CPU0 (default)     */
#define APP_INFER_PPU       1   /* IMAI_compute offloaded to the PPU (ARC EV) core */

#ifndef APP_INFER
#define APP_INFER           APP_INFER_PPU
#endif

/* ---- APP_MODE ----------------------------------------------------------- */
#define APP_MODE_STREAM   0   /* stream input/output to a host over a transport   */
#define APP_MODE_LOCAL    1   /* run built-in input samples; self-test vs expected */

#ifndef APP_MODE
#define APP_MODE          APP_MODE_STREAM
#endif

/* ---- APP_TRANSPORT (only relevant when APP_MODE == APP_MODE_STREAM) ------ */
#define APP_TRANSPORT_ETH   0   /* protocol over TCP (port 14325), needs lwIP  */
#define APP_TRANSPORT_UART  1   /* protocol over ASCLIN0 (binary, 3 Mbaud), this mode is currently not functional     */

#ifndef APP_TRANSPORT
#define APP_TRANSPORT       APP_TRANSPORT_ETH
#endif

/* ---- Ethernet addressing (only relevant when the TCP transport is used) -- *
 * Set APP_ETH_STATIC_IP to 1 to use a fixed IP instead of DHCP. Edit the
 * dotted-decimal address, netmask and gateway strings below. */
#ifndef APP_ETH_STATIC_IP
#define APP_ETH_STATIC_IP   1
#endif

#ifndef APP_ETH_IP_ADDR
#define APP_ETH_IP_ADDR     "169.254.0.197"
#endif
#ifndef APP_ETH_NETMASK
#define APP_ETH_NETMASK     "255.255.255.0"
#endif
#ifndef APP_ETH_GATEWAY
#define APP_ETH_GATEWAY     "169.254.0.1"
#endif

/* ==== Tunables (safe to edit for your model / setup) ===================== */

/* ---- Serial console / transport ----------------------------------------- */
#ifndef APP_DEBUG_UART_BAUDRATE
#define APP_DEBUG_UART_BAUDRATE   115200u    /* ASCLIN0 printf console (non-UART-transport builds) */
#endif
#ifndef APP_STREAM_UART_BAUDRATE
#define APP_STREAM_UART_BAUDRATE  3000000u   /* ASCLIN0 binary protocol baud (UART transport)      */
#endif
#ifndef APP_STREAM_TCP_PORT
#define APP_STREAM_TCP_PORT       14325      /* DEEPCRAFT protocol TCP port (Ethernet transport)   */
#endif

/* ---- Local self-test (APP_MODE_LOCAL) ----------------------------------- *
 * Max abs error for a PASS. */
#ifndef APP_SELFTEST_TOLERANCE
#define APP_SELFTEST_TOLERANCE     0.05f
#endif

/* ---- Model I/O buffer bounds -------------------------------------------- *
 * Upper bounds (in BYTES) on the model input/output, TOTALLED ACROSS ALL input
 * tensors / all output tensors. Bytes rather than elements because a model may
 * mix element types (int8/int16/int32/float32) across its tensors; each tensor
 * starts on a PPU_TENSOR_ALIGN boundary in the mailbox, so allow for a little
 * padding between tensors of different widths (see ppu_ipc.h).
 * Size the self-test vectors (APP_MODE_LOCAL) and, for PPU inference, the
 * TriCore<->PPU shared IPC buffers. The actual per-model sizes come from the
 * model metadata at run time; raise these only if a model's total I/O exceeds
 * them. NOTE: for PPU inference these size the shared IPC struct, so BOTH
 * images (TriCore + PPU) must be rebuilt and flashed together after a change. */
#ifndef APP_MODEL_MAX_INPUT_BYTES
#define APP_MODEL_MAX_INPUT_BYTES   8000u
#endif
#ifndef APP_MODEL_MAX_OUTPUT_BYTES
#define APP_MODEL_MAX_OUTPUT_BYTES   256u
#endif

/* Upper bound on the number of separate input tensors / output tensors a MIMO
 * model can have (mirrors PPU_META_MAX_TENSORS in ppu_ipc.h). Raise if a model
 * has more inputs or more outputs than this. */
#ifndef APP_MODEL_MAX_TENSORS
#define APP_MODEL_MAX_TENSORS         8u
#endif

/* Upper bound on the number of PPU profiling regions reported to CPU0
 * (APP_INFER_PPU). */
#ifndef APP_PPU_MAX_REGIONS
#define APP_PPU_MAX_REGIONS           8u
#endif

/* Max time CPU0 waits for one PPU inference before giving up (wedge guard), in
 * STM ticks. Long enough for any real inference, short enough to recover the
 * link for diagnosis. */
#ifndef APP_PPU_DISPATCH_TIMEOUT_TICKS
#define APP_PPU_DISPATCH_TIMEOUT_TICKS  (5000000000ULL)
#endif

/* ---- Derived flags (do not edit) ---------------------------------------- */

/* Non-zero when inference is offloaded to the PPU (pulls in the PPU interface,
 * the shared IPC region and the PPU boot/dispatch path). */
#if APP_INFER == APP_INFER_PPU
#define APP_USE_PPU        1
#else
#define APP_USE_PPU        0
#endif

/* The Ethernet/lwIP stack is only built/linked for the TCP transport. */
#if (APP_MODE == APP_MODE_STREAM) && (APP_TRANSPORT == APP_TRANSPORT_ETH)
#define APP_USE_ETHERNET   1
#else
#define APP_USE_ETHERNET   0
#endif

/* When the UART streaming transport owns ASCLIN0 for the binary protocol,
 * printf must be redirected into the protocol's Debug Log device instead of an
 * ASCLIN0 debug console (raw printf would corrupt the protocol framing).
 * serialio.c and dev_log.c switch their write() retarget on
 * CONFIG_STREAMING_LOG_REDIRECT, which we define here for that build only. */
#if (APP_MODE == APP_MODE_STREAM) && (APP_TRANSPORT == APP_TRANSPORT_UART)
#define APP_UART_TRANSPORT  1
#ifndef CONFIG_STREAMING_LOG_REDIRECT
#define CONFIG_STREAMING_LOG_REDIRECT
#endif
#else
#define APP_UART_TRANSPORT  0
#endif

/* Human-readable build description for the boot banner. */
#if APP_MODE == APP_MODE_LOCAL
#define APP_BUILD_DESC   "local self-test"
#elif APP_USE_ETHERNET
#define APP_BUILD_DESC   "Ethernet/TCP transport"
#else
#define APP_BUILD_DESC   "UART transport"
#endif

/* Where inference runs, for the boot banner. */
#if APP_USE_PPU
#define APP_INFER_DESC   "PPU (ARC EV)"
#else
#define APP_INFER_DESC   "TriCore CPU0"
#endif

#endif /* APP_CONFIG_H */
