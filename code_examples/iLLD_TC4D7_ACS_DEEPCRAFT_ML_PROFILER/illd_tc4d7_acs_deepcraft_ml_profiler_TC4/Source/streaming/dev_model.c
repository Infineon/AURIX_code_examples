#define IMAGINET_TYPES_D16      (0x62)
#define IMAGINET_TYPES_D32      (0x64)
#define IMAGINET_TYPES_UINT8    (0x71)
#define IMAGINET_TYPES_UINT16   (0x72)
#define IMAGINET_TYPES_UINT32   (0x74)
