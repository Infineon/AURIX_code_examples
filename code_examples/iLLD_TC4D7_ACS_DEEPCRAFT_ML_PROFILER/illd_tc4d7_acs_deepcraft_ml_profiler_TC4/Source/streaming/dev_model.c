#define IMAGINET_TYPES_FLOAT32  (0x14)
#define IMAGINET_TYPES_FLOAT64  (0x18)
#define IMAGINET_TYPES_INT8     (0x21)
#define IMAGINET_TYPES_INT16    (0x22)
