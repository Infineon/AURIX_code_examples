/*
 * Debug-log device (see dev_log.h).
 *
 * The newlib write() syscall is retargeted here: instead of writing raw bytes to the UART
 * (which would corrupt the binary protocol on ASCLIN0), captured text is pushed into a ring
 * buffer. When the host has started this device the buffered bytes are streamed back as U8
 * DataChunks from the poll callback, i.e. only between complete protocol messages.
 */

#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

#include "dev_log.h"
#include "protocol/protocol.h"
#include "protocol/pb_encode.h"

/*******************************************************************************
 * Log ring buffer
 ******************************************************************************/

#define LOG_RING_SIZE (4096U)

static uint8_t  s_ring[LOG_RING_SIZE];
static uint32_t s_head;   /* next write position */
static uint32_t s_tail;   /* next read position  */
static uint32_t s_count;  /* bytes currently buffered */

/* Append one byte, dropping the oldest byte on overflow. Runs in the single
 * CPU0 cooperative context (write() / poll), so no locking is required. */
static void _ring_push(uint8_t b)
{
    if (s_count == LOG_RING_SIZE)
    {
        /* Buffer full: discard the oldest byte. */
        s_tail = (s_tail + 1U) % LOG_RING_SIZE;
        s_count--;
    }
    s_ring[s_head] = b;
    s_head = (s_head + 1U) % LOG_RING_SIZE;
    s_count++;
}

/*******************************************************************************
 * Device context
 ******************************************************************************/

typedef struct
{
    protocol_t    *protocol;
    int            device_id;
    const uint8_t *flush_ptr;   /* contiguous region being sent by the callback */
    int            flush_len;
} dev_log_t;

/*******************************************************************************
 * newlib retarget
 ******************************************************************************/

#include "app_config.h"
#include "serialio.h"

#if (defined(__HIGHTEC__) || defined(__GNUC__))
/* Retarget stdout/stderr. Text is always captured into the log ring buffer so
 * the protocol "Debug Log" device can stream it to the host (over TCP or UART).
 * When the UART is NOT the protocol transport it is additionally echoed to the
 * physical ASCLIN0 console for local debugging. In UART-transport mode the
 * console echo is skipped so the raw binary protocol stream is not corrupted. */
int write(int desc, void *buf, size_t len)
{
    (void)desc;

    const uint8_t *p = (const uint8_t *)buf;
    for (size_t i = 0; i < len; i++)
    {
        _ring_push(p[i]);
    }

#if !APP_UART_TRANSPORT
    SERIALIO_Write(buf, (int)len);
#endif

    return (int)len;
}
#endif

/*******************************************************************************
 * Payload writer (board -> host)
 ******************************************************************************/

static bool _write_log_payload(
    protocol_t   *protocol,
    int           device_id,
    int           stream_id,
    int           frame_count,
    int           total_bytes,
    pb_ostream_t *ostream,
    void         *arg)
{
    (void)protocol;
    (void)device_id;
    (void)stream_id;
    (void)frame_count;

    dev_log_t *log = (dev_log_t *)arg;
    return pb_write(ostream, (const pb_byte_t *)log->flush_ptr, total_bytes);
}

/*******************************************************************************
 * Device manager callbacks
 ******************************************************************************/

static bool _configure_streams(protocol_t *protocol, int device_id, void *arg)
{
    (void)arg;

    protocol_clear_streams(protocol, device_id);

    int stream_id = protocol_add_stream(
        protocol,
        device_id,
        "Log",
        protocol_StreamDirection_STREAM_DIRECTION_OUTPUT,
        protocol_DataType_DATA_TYPE_U8,
        0.0f,   /* asynchronous / irregular */
        -1,     /* unlimited frames per DataChunk */
        "text");
    if (stream_id < 0)
    {
        protocol_set_device_status(protocol, device_id,
            protocol_DeviceStatus_DEVICE_STATUS_ERROR, "Failed to add log stream");
        return false;
    }

    protocol_add_stream_rank(protocol, device_id, stream_id, "Byte", 1, NULL);

    protocol_set_device_status(protocol, device_id,
        protocol_DeviceStatus_DEVICE_STATUS_READY, NULL);
    return true;
}

static void _start(protocol_t *protocol, int device_id, pb_ostream_t *ostream, void *arg)
{
    (void)ostream;
    (void)arg;

    protocol_set_device_status(protocol, device_id,
        protocol_DeviceStatus_DEVICE_STATUS_ACTIVE, NULL);
}

static void _stop(protocol_t *protocol, int device_id, pb_ostream_t *ostream, void *arg)
{
    (void)ostream;
    (void)arg;

    protocol_set_device_status(protocol, device_id,
        protocol_DeviceStatus_DEVICE_STATUS_READY, NULL);
}

static void _poll(protocol_t *protocol, int device_id, pb_ostream_t *ostream, void *arg)
{
    dev_log_t *log = (dev_log_t *)arg;

    /* Drain the ring buffer, one contiguous slice per DataChunk (handles the
     * wrap-around in a subsequent iteration). Safe here: no protocol message is
     * mid-encode when poll runs. */
    while (s_count > 0)
    {
        uint32_t contiguous = LOG_RING_SIZE - s_tail;
        if (contiguous > s_count)
        {
            contiguous = s_count;
        }

        log->flush_ptr = &s_ring[s_tail];
        log->flush_len = (int)contiguous;

        if (protocol_send_data_chunk(
                protocol, device_id, 0, (int)contiguous, 0, ostream,
                _write_log_payload) != PROTOCOL_STATUS_SUCCESS)
        {
            break;
        }

        s_tail = (s_tail + contiguous) % LOG_RING_SIZE;
        s_count -= contiguous;
    }
}

/*******************************************************************************
 * Registration
 ******************************************************************************/

int dev_log_register(protocol_t *protocol)
{
    dev_log_t *log = (dev_log_t *)calloc(1, sizeof(dev_log_t));
    if (log == NULL)
    {
        return PROTOCOL_STATUS_MEMORY_ERROR;
    }

    log->protocol = protocol;

    device_manager_t manager = {
        .arg               = log,
        .busy              = NULL,
        .configure_streams = _configure_streams,
        .start             = _start,
        .stop              = _stop,
        .poll              = _poll,
        .data_received     = NULL,
    };

    int device_id = protocol_add_device(
        protocol,
        protocol_DeviceType_DEVICE_TYPE_OTHER,
        "Debug Log",
        "Firmware debug/printf output",
        manager);
    if (device_id < 0)
    {
        return device_id;
    }

    log->device_id = device_id;

    _configure_streams(protocol, device_id, log);

    return device_id;
}
