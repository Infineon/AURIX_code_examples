/* Upper bound on how long CPU0 waits for the PPU before giving up. */
#define PPU_DISPATCH_TIMEOUT_TICKS  APP_PPU_DISPATCH_TIMEOUT_TICKS

/* Set after a timeout: the PPU is still working on the previous input, so its
 * next 'done' belongs to that one and has to be discarded. */
static bool s_desynced = false;

/* Spin on a shared flag until it is set or the timeout elapses. */
static bool _wait(volatile uint32 *flag)
{
    uint64_t start = IfxStm_get(&MODULE_CPU0);

    while (*flag == 0u)
    {
        if ((IfxStm_get(&MODULE_CPU0) - start) > PPU_DISPATCH_TIMEOUT_TICKS)
        {
            return false;
        }
    }
    return true;
}

/* Describe the fatal PPU exception recorded in the IPC block, if there is one.
 * A silent PPU is usually a trapped PPU, and the capture is the only evidence
 * left once the core has stopped (see PPU/Ppu_Fault.c). */
static void _report_fault(const TcPpuIpcData *ipc)
{
    uint32_t    vec = (ipc->fault_ecr >> 16) & 0xFFu;  /* ARCv2 ECR: [23:16] vector */
    const char *what;

    if (ipc->fault_ready == 0u)
    {
        return;
    }

    if ((ipc->fault_kind & PPU_FAULT_KIND_MASK) == PPU_FAULT_KIND_HAL_FAULT)
    {
        what = ((ipc->fault_kind & ~PPU_FAULT_KIND_MASK) == PPU_HAL_FAULT_SHUTDOWN)
                   ? "HAL shutdown after fatal exception"
                   : "HAL fault";
    }
    else
    {
        what = (ipc->fault_msg[0] != '\0') ? ipc->fault_msg : "CPU exception";
    }

    printf("[ppu] FATAL: %s (kind=0x%08lX) ecr=0x%08lX%s efa=0x%08lX "
           "pc=0x%08lX vec_pc=0x%08lX vec_sp=0x%08lX\r\n",
           what,
           (unsigned long)ipc->fault_kind,
           (unsigned long)ipc->fault_ecr,
           (vec == PPU_ECR_VECTOR_PROTV) ? " (EV_ProtV)" : "",
           (unsigned long)ipc->fault_efa,
           (unsigned long)ipc->fault_eret,
           (unsigned long)ipc->fault_vec_pc,
           (unsigned long)ipc->fault_vec_sp);

    /* Both stacks grow down, so a fault address (or vector stack pointer) below
     * the corresponding base means that stack overflowed. */
    if (ipc->stack_base_addr != 0u && ipc->fault_efa != 0u &&
        ipc->fault_efa < ipc->stack_base_addr &&
        (ipc->stack_base_addr - ipc->fault_efa) < PPU_STACK_OVERFLOW_WINDOW)
    {
        printf("[ppu] cause: SCALAR STACK OVERFLOW (%lu bytes below the stack base "
               "0x%08lX; stack is 0x%08lX..0x%08lX)\r\n",
               (unsigned long)(ipc->stack_base_addr - ipc->fault_efa),
               (unsigned long)ipc->stack_base_addr,
               (unsigned long)ipc->stack_base_addr,
               (unsigned long)ipc->stack_top_addr);
        printf("[ppu] raise LCF_STACKSIZE in the PPU linker script, or raise the "
               "optimisation level\r\n");
    }
    else if (ipc->vstack_base_addr != 0u && ipc->fault_vec_sp != 0u &&
             ipc->fault_vec_sp <= ipc->vstack_base_addr)
    {
        printf("[ppu] cause: VECTOR STACK OVERFLOW (sp 0x%08lX at/below the stack base "
               "0x%08lX; %lu bytes were available)\r\n",
               (unsigned long)ipc->fault_vec_sp,
               (unsigned long)ipc->vstack_base_addr,
               (unsigned long)ipc->vstack_total_bytes);
        printf("[ppu] free VCCM by moving tensors to CSM at export time, or raise the "
               "optimisation level\r\n");
    }
}

/* Consume and discard the completion left over from a timed-out inference,
 * otherwise every later sample is served the previous result. */
static void _resync(TcPpuIpcData *ipc)
{
    if (!s_desynced)
    {
        return;
    }

    if (_wait(&ipc->done))
    {
        ipc->done  = 0u;
        s_desynced = false;
        printf("[ppu] resynchronised after timeout\r\n");
    }
}

bool ppu_dispatch_wait_meta_ready(void)
{
    return _wait(&ppuInterfaceData.ppuIpcDataPtr->meta.ready);
}

bool ppu_dispatch_run(const void *const *input_buffers, void *const *output_buffers)
{
    TcPpuIpcData *ipc = ppuInterfaceData.ppuIpcDataPtr;
    uint32        i;

    _resync(ipc);

    /* Gather every input tensor into the mailbox, concatenated in metadata
     * order (see the TcPpuIpcData layout comment in ppu_ipc.h). */
    for (i = 0u; i < ipc->meta.input_count; i++)
    {
        memcpy(ipc->input + PpuMeta_inputOffsetBytes(&ipc->meta, i),
               input_buffers[i],
               (size_t)ipc->meta.inputs[i].bytes);
    }

    ipc->done    = 0u;
    ipc->request = 1u;   /* written last: signals a new input is ready */

    /* Bounded wait: a PPU stall must not wedge the caller. */
    if (_wait(&ipc->done))
    {
        if (ipc->output_valid == 0u)
        {
            printf("[ppu] the PPU refused to run this model (see its own bounds check)\r\n");
            return false;
        }

        for (i = 0u; i < ipc->meta.output_count; i++)
        {
            memcpy(output_buffers[i],
                   ipc->output + PpuMeta_outputOffsetBytes(&ipc->meta, i),
                   (size_t)ipc->meta.outputs[i].bytes);
        }
        return true;
    }

    printf("[ppu] inference timeout (done=%lu request=%lu)\r\n",
           (unsigned long)ipc->done, (unsigned long)ipc->request);
    _report_fault(ipc);

    s_desynced = true;
    return false;
}
