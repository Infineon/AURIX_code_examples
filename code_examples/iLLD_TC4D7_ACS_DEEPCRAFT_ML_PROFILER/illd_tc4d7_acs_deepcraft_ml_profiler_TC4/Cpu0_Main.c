/*
 * DEEPCRAFT streaming firmware entry point.
 *
 * The build is configured at compile time via Source/app_config.h:
 *   - APP_MODE_LOCAL  : run built-in input samples through the model and
 *                       self-test against baked-in expected outputs (no host).
 *   - APP_MODE_STREAM : stream I/O with a host over the selected transport:
 *       - APP_TRANSPORT_ETH  : DEEPCRAFT protocol over TCP (FreeRTOS + lwIP).
 *       - APP_TRANSPORT_UART : DEEPCRAFT protocol over ASCLIN0 (binary).
 * All builds run under FreeRTOS.
 */
void core0_main(void)
{
    IfxCpu_enableInterrupts();

    /* !!WATCHDOG0 AND SAFETY WATCHDOG ARE DISABLED HERE!! */
    IfxWtu_disableCpuWatchdog(IfxWtu_getCpuWatchdogPassword());
    IfxWtu_disableSystemWatchdog(IfxWtu_getSystemWatchdogPassword());

    /* Initialise any DAVE APPs before the hand-written peripheral bring-up. */
    if (DAVE_Init() != DAVE_STATUS_SUCCESS)
    {
        for (;;)
        {
            __nop();
        }
    }

#if !APP_UART_TRANSPORT
    /* ASCLIN0 is the printf debug console (TCP transport or local self-test).
     * In the UART-transport build ASCLIN0 carries the binary protocol instead,
     * and printf is redirected to the Debug Log device (dev_log.c). */
    SERIALIO_Init(DEBUG_UART_BAUDRATE);
#endif
    printf("\r\n=== AURIX TC4D7 streaming firmware (%s, inference on %s) ===\r\n",
           APP_BUILD_DESC, APP_INFER_DESC);

#if APP_USE_PPU
    /* Bring up the PPU (ARC EV) inference core before the scheduler starts:
     * grant bus access to the masters, boot the PPU and block until it signals
     * that it is ready (ppu_interface_start_ppu). The DEEPCRAFT protocol still
     * runs entirely on CPU0; only IMAI_compute is dispatched to the PPU. */
    printf("[ppu] granting bus access to masters (LMU + PPUC)...\r\n");
    allowAccess();
    printf("[ppu] starting PPU (ARC EV) core; waiting for boot handshake...\r\n");
    ppu_interface_start_ppu();
    printf("[ppu] PPU booted; inference is offloaded to the PPU\r\n");
#endif

    if (xTaskCreate(app_task, "app", configMINIMAL_STACK_SIZE * 8,
                    NULL, tskIDLE_PRIORITY + 1, NULL) != pdPASS)
    {
        printf("Failed to create app task\r\n");
    }

    vTaskStartScheduler();

    /* The scheduler should never return. */
    for (;;)
    {
        __nop();
    }
}

static void app_task(void *arg)
{
    (void)arg;

#if APP_MODE == APP_MODE_LOCAL
    /* No host / transport: run the built-in samples and self-test the model.
     * Delay briefly first so a serial terminal has time to attach after reset
     * and capture the (one-shot) result on the ASCLIN0 console. */
    vTaskDelay(pdMS_TO_TICKS(3000));
    (void)local_selftest_run();
    for (;;)
    {
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
#else
    /* Stream mode: transport-agnostic protocol + devices (debug log first so
     * early messages are captured, then the DEEPCRAFT inference model). */
    protocol_Version firmware_version = {
        .major    = 1,
        .minor    = 0,
        .build    = 0,
        .revision = 0
    };
    protocol_t *protocol = protocol_create(
        "AURIX TC4D7 Lite Kit", STREAM_SERIAL_UUID, firmware_version);
    if (protocol == NULL)
    {
        printf("[app] protocol_create failed (out of memory)\r\n");
        vTaskDelete(NULL);
        return;
    }
    dev_log_register(protocol);
    dev_model_register(protocol);

#if APP_USE_ETHERNET
    /* Bring up Ethernet, wait for link + DHCP, then serve the protocol over TCP. */
    eth_start();
    while (!eth_is_ready())
    {
        vTaskDelay(pdMS_TO_TICKS(200));
    }
    printf("[app] Ethernet ready - TCP streaming server on port %u\r\n",
           (unsigned)STREAM_TCP_PORT);
    tcp_stream_serve(protocol, STREAM_TCP_PORT);   /* never returns */
#else
    /* UART streaming transport: ASCLIN0 carries the binary protocol and printf
     * is redirected to the Debug Log device. */
    static uart_stream_t stream;
    uart_stream_init(&stream, protocol, STREAM_UART_BAUDRATE);
    printf("[app] UART streaming transport ready (%u baud)\r\n",
           (unsigned)STREAM_UART_BAUDRATE);
    for (;;)
    {
        protocol_process_request(protocol, &stream.istream, &stream.ostream);
    }
#endif /* APP_USE_ETHERNET */
#endif /* APP_MODE */
}

/* FreeRTOS hook (configCHECK_FOR_STACK_OVERFLOW=1): report and halt so an
 * overflowing task stack is caught during bring-up instead of silently
 * corrupting memory. */
void vApplicationStackOverflowHook(TaskHandle_t xTask, char *pcTaskName)
{
    (void)xTask;
    printf("[FATAL] stack overflow in task '%s'\r\n", pcTaskName ? pcTaskName : "?");
    for (;;)
    {
        __nop();
    }
}
