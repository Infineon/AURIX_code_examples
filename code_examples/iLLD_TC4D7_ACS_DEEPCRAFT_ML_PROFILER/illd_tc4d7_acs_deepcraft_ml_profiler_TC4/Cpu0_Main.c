/* 16-byte serial UUID used by the host software to identify this board. */
static const uint8 STREAM_SERIAL_UUID[16] = {
    0x54, 0x43, 0x34, 0x44, 0x37, 0x4C, 0x4B, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01
};

