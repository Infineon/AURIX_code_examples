#define MAX_FAIL_COUNT                  3                        /* Maximum number of allowed failures */

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
IfxSmmRst_Reset g_resetStatus;  /* Stores information of the triggered reset */

/*********************************************************************************************************************/
/*--------------------------------------------structure--------------------------------------------*/
/*********************************************************************************************************************/
/* Expected Safety LBIST Signature (MISR) for the TC4Dx device */
typedef union{
    struct{
        uint16 dom0Failed:1;
        uint16 dom1Failed:1;
        uint16 dom2Failed:1;
        uint16 dom3Failed:1;
        uint16 dom4Failed:1;
        uint16 dom5Failed:1;
        uint16 dom6Failed:1;
        uint16 dom7Failed:1;

        uint16 notDone:1;
        uint16 notTerminatedProperlyLBTERM:1;   /* LBIST was not properly terminated for respective domains */
        uint16 earlyTerminatedPORST:1; /* LBIST termination due to warm PORST */
        uint16 unused:5;
    };
    uint16 lbistKeyoffStatus;
} LbistkeyoffStatus;

typedef struct
{
    boolean oneEyeLed0LbistPassed;
    boolean oneEyeLed1WrongLbist;
    boolean oneEyeLed2LbistFailed;
    boolean oneEyeLed3LbistNotExecuted;
} LbistStatusLeds;

LbistStatusLeds g_LbistStatusLeds;

LbistkeyoffStatus g_LbistKeyoffStatus;

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/
uint8 getSafetyIndication(void);
uint8 getSessionIndication(void);
void resetLbistStatusLeds(void);
void triggerLbistKeyoff(void);
void handleLbistKeyoffCompleted(void);

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
/*
 * get the safety indication for key-off
 * */
uint8 getSafetyIndication(void)
{
    uint8 safetyIndication;
    safetyIndication    = MODULE_TRI.LBIST.STAT.TEST.B.SAFEIND;
    return safetyIndication;
}

/*
 * LBIST was triggered by a key-off request — results belong to a key-off run, not key-on
 * */
uint8 getSessionIndication(void)
{
    uint8 sessionIndication;
    sessionIndication    = MODULE_TRI.LBIST.STAT.TEST.B.KEYIND;
    return sessionIndication;
}

/*
 * Resets all LBIST status LEDs to their default (off) state
 * */
void resetLbistStatusLeds(void)
{
    /* reset the OneEye GUI LEDs */
    g_LbistStatusLeds.oneEyeLed0LbistPassed = FALSE;
    g_LbistStatusLeds.oneEyeLed1WrongLbist = FALSE;
    g_LbistStatusLeds.oneEyeLed2LbistFailed = FALSE;
    g_LbistStatusLeds.oneEyeLed3LbistNotExecuted = FALSE;
}

/*
 * Clears reset status registers and re-triggers an LBIST key-off run
 * */
void triggerLbistKeyoff(void)
{
    /* Clear reset status registers */
    IfxSmmRst_clearAllResetRegisters();

    /* trigger LBIST safety test */
    IfxTriLbist_triggerInline(&IfxTriLbist_keyOffDefaultConfig);
}

/*
 * Evaluates the LBIST key-off result
 * */
void handleLbistKeyoffCompleted(void)
 {
    /* reset LEDs to default state */
    resetLbistStatusLeds();

    /*
     * if the last reset was a Cold Power On Reset OR
     * if the last reset was a warm Power On Reset
     * */
    if ((g_resetStatus.resetStatus.B.CLDPORST == 1) ||
        (g_resetStatus.resetStatus.B.PORST == 1))
    {
        /*
         * No external PORST interrupted LBIST and
         * LBIST terminated properly and
         * LBIST done global and each domain
         * verify the signature values for each domain
         * */
        g_LbistKeyoffStatus.lbistKeyoffStatus = IfxTriLbist_evaluateResult(
                &IfxTriLbist_keyOffDefaultConfig.signature[0]);

        /* check if Lbist key-off successfully executed
         * coming first power on session, there will be no LBIST trigger by FW*/
        if (TRUE == IfxTriLbist_isDone())
        {
            /* is the LBIST run a key-off i.e safety indication and session indication whether key-on or key-off run*/
            boolean isKeyoffRun =
                    (IfxTriLbist_keyOffDefaultConfig.safetySelEnable == getSafetyIndication()) &&
                     (IfxTriLbist_keyOffDefaultConfig.keyoffEnable == getSessionIndication());

            /* This function clears LBIST Status registers and brings LBIST module to its default state */
            IfxTriLbist_resetLbist();

            /* LBIST key-off status successful and was Key-off LBIST */
            if ((IFXTRILBIST_SUCCESS == g_LbistKeyoffStatus.lbistKeyoffStatus) &&
                (TRUE == isKeyoffRun))
            {
                g_LbistStatusLeds.oneEyeLed0LbistPassed = TRUE;
            }
            /* LBIST key-off status successful and was wrong LBIST */
            else if((IFXTRILBIST_SUCCESS == g_LbistKeyoffStatus.lbistKeyoffStatus) &&
                    (FALSE == isKeyoffRun))
            {
                g_LbistStatusLeds.oneEyeLed1WrongLbist = TRUE;
            }
            /* LBIST key-off status not successful */
            else
            {
                g_LbistStatusLeds.oneEyeLed2LbistFailed = TRUE;
            }
        }
        else
        {
            /* trigger the LBIST key-off*/
            triggerLbistKeyoff();
        }
    }
    else
    {
        /* it is not coming from cold PORST/warm PORST, therefore, no LBIST trigger */
        g_LbistStatusLeds.oneEyeLed3LbistNotExecuted = TRUE;
    }
}

/*
 * Coordinates the LBIST key-off check: captures reset status, evaluates the result, then clears reset registers
 * */
void processLbistKeyoff(void)
{
    /* Get the last Reset status */
    IfxSmmRst_evaluateReset(&g_resetStatus);

    /* Evaluate LBIST key on */
    handleLbistKeyoffCompleted();

    /* Clear reset status registers */
    IfxSmmRst_clearAllResetRegisters();
}
