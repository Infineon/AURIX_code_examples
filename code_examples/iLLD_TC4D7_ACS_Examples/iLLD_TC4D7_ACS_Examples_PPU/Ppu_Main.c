#include <stdint.h>
#include <arc_vector.h>
#include <kernels.h>


 /* API to signal that PPU bootup is done.
  * This is done by triggering the PPUC Inter core communication interrupt up.
  * If one of the TriCores are configured to receive the interrupt (or poll),
  * then such communication is established.
  */
 /**  General purpose group 0 service request 0 */
 #define SRC_GPSR0_SR0 /*lint --e(923, 9078)*/ (*(volatile uint32_t*)0xF4433460u)
 static void TriCoreInterface_flagPpuBootedUp(void)
 {
     while (SRC_GPSR0_SR0 & 0x1000000 );
     SRC_GPSR0_SR0 |= 0x4000000;
 }

 
 int main(void)
 {
     /* disable MPU protection of the PPU */
     _sr(0, 0x409);

     /* Notifies CPU0 that PPU is booted up */
     TriCoreInterface_flagPpuBootedUp();

     kernel_main();

     while (1==1){}
     return 0;
 }
