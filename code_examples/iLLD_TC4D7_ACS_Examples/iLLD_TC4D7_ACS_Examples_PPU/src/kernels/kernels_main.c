/**
 * Unified main entry point for all kernel benchmarks.
 * Calls each kernel's test function and reports overall results.
 */

#include <arc_vector.h>
#include <stdio.h>
#include "kernels/kernels.h"


/* Global results array — populated by each test function */
kernel_result_t kernel_results[NUM_KERNELS];

/* Test function declarations (defined in tests/) */
extern bool test_vadd8(void);
extern bool test_vscale(void);
extern bool test_dot(void);
extern bool test_vmax(void);
extern bool test_vclamp(void);
extern bool test_wsum(void);
extern bool test_vadd_sat(void);

bool total_pass = true; /*is all code shows expected behavior.*/

int kernel_main(void)
{

    /* Run all kernel tests (results stored in kernel_results[]) */

    total_pass &= test_vadd8();
    total_pass &= test_vscale();
    total_pass &= test_dot();
    total_pass &= test_vmax();
    total_pass &= test_vclamp();
    total_pass &= test_wsum();
    total_pass &= test_vadd_sat();


    _sr(1, 0x47); /* invalidate the cache so that kernel_results[] are visible in the debugger.*/

    return total_pass ? 0 : 1;
}
