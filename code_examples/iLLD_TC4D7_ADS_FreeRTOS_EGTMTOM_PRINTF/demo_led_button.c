#include "demo_led_button.h"

#include "FreeRTOS.h"
#include "task.h"

#include "bsp/kit_tc4d7_lite.h"

#include "Ifx_Types.h"

#include "Port/Std/IfxPort.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define LED1_TOGGLE_PERIOD_MS              500U
#define BUTTON_POLL_PERIOD_MS              20U

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*--------------------------------------------Private Variables/Constants--------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/
static void handle_button_input(boolean *wasButtonPressed);
static void handle_led_blink(uint32 *ledElapsedMs);

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
/*******************************************************************************
* Function Name: handle_led_and_button_task
********************************************************************************
* Summary:
* Toggle LED1 cyclically and toggle LED2 on each BUTTON1 press.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
void handle_led_and_button_task(void *pvParameters)
{
    TickType_t xLastWakeTime = xTaskGetTickCount();
    uint32 ledElapsedMs = 0U;
    boolean wasButtonPressed = FALSE;

    (void)pvParameters;

    while (1)
    {
        handle_button_input(&wasButtonPressed);
        handle_led_blink(&ledElapsedMs);

        vTaskDelayUntil(&xLastWakeTime, pdMS_TO_TICKS(BUTTON_POLL_PERIOD_MS));
    }
}

/*******************************************************************************
* Function Name: handle_button_input
********************************************************************************
* Summary:
* Poll BUTTON1 and toggle LED2 on each button press edge.
*
* Parameters:
*  wasButtonPressed: Pointer to the previous button state.
*
* Return:
*  none
*
*******************************************************************************/
static void handle_button_input(boolean *wasButtonPressed)
{
    boolean isButtonPressed = (IfxPort_getPinState(BOARD_USER_BUTTON_1.port,
                                                   BOARD_USER_BUTTON_1.pinIndex) == FALSE);

    if ((isButtonPressed != FALSE) && (*wasButtonPressed == FALSE))
    {
        IfxPort_togglePin(BOARD_USER_LED_2.port, BOARD_USER_LED_2.pinIndex);
    }

    *wasButtonPressed = isButtonPressed;
}

/*******************************************************************************
* Function Name: handle_led_blink
********************************************************************************
* Summary:
* Toggle LED1 periodically based on the task polling interval.
*
* Parameters:
*  ledElapsedMs: Pointer to the elapsed LED timing state.
*
* Return:
*  none
*
*******************************************************************************/
static void handle_led_blink(uint32 *ledElapsedMs)
{
    *ledElapsedMs += BUTTON_POLL_PERIOD_MS;

    if (*ledElapsedMs >= LED1_TOGGLE_PERIOD_MS)
    {
        IfxPort_togglePin(BOARD_USER_LED_1.port, BOARD_USER_LED_1.pinIndex);
        *ledElapsedMs = 0U;
    }
}
