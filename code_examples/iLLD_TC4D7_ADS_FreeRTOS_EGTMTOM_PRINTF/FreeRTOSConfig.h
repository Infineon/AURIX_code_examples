/* Default definition of configASSERT(). */
#ifdef DEBUG
#ifdef __TASKING__
#define configASSERT(x)                         \
    do                                          \
    {                                           \
        if ((x) == 0)                           \
        {                                       \
            __disable();                        \
            __debug();                          \
        }                                       \
    } while (0)
#endif
#if defined(__HIGHTEC__) && defined(__clang__)
#define configASSERT(x)                         \
    do                                          \
    {                                           \
        if ((x) == 0)                           \
        {                                       \
            __builtin_tricore_disable();        \
            __builtin_tricore_debug();          \
        }                                       \
    } while (0)
#endif
#if defined(__GNUC__) && !defined(__HIGHTEC__)
#define configASSERT(x)                         \
    do                                          \
    {                                           \
        if ((x) == 0)                           \
        {                                       \
            __builtin_tricore_disable();        \
            __builtin_tricore_debug();          \
        }                                       \
    } while (0)
#endif
#else
#define configASSERT(x)
#endif

