#include "demo_print_timer.h"

#include <stdio.h>

#include "Ifx_Types.h"

#include "Cpu/Irq/IfxCpu_Irq.h"
#include "Egtm/Tom/Timer/IfxEgtm_Tom_Timer.h"

/*********************************************************************************************************************/
/*------------------------------------------------------Macros-------------------------------------------------------*/
/*********************************************************************************************************************/
#define TOM_TIMER_FREQUENCY_HZ          1.0f
#define TOM_TIMER_ISR_PRIORITY          31
#define TOM_TIMER_CLUSTER               IfxEgtm_Cluster_0
#define TOM_TIMER_CHANNEL               IfxEgtm_Tom_Ch_0

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
static TaskHandle_t g_printTaskHandle = NULL;
static IfxEgtm_Tom_Timer g_timerDriver;

/*********************************************************************************************************************/
/*--------------------------------------------Private Variables/Constants--------------------------------------------*/
/*********************************************************************************************************************/

/*********************************************************************************************************************/
/*------------------------------------------------Function Prototypes------------------------------------------------*/
/*********************************************************************************************************************/
static void init_egtm_tom_timer(void);

IFX_INTERRUPT(egtm_tom_timer_isr, 0, TOM_TIMER_ISR_PRIORITY);

/*********************************************************************************************************************/
/*---------------------------------------------Function Implementations----------------------------------------------*/
/*********************************************************************************************************************/
/*******************************************************************************
* Function Name: demo_print_timer_set_task_handle
********************************************************************************
* Summary:
* Store the print task handle used by the timer interrupt.
*
* Parameters:
*  printTaskHandle: Handle of the print task created by the application.
*
* Return:
*  none
*
*******************************************************************************/
void demo_print_timer_set_task_handle(TaskHandle_t printTaskHandle)
{
    g_printTaskHandle = printTaskHandle;
}

/*******************************************************************************
* Function Name: demo_print_timer_init
********************************************************************************
* Summary:
* Initialize the timer that periodically notifies the print task.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
void demo_print_timer_init(void)
{
    init_egtm_tom_timer();
}

/*******************************************************************************
* Function Name: handle_print_notification_task
********************************************************************************
* Summary:
* Wait for task notifications from the eGTM TOM ISR and print a message.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
void handle_print_notification_task(void *pvParameters)
{
    uint32 notificationCount;

    (void)pvParameters;

    while (1)
    {
        notificationCount = ulTaskNotifyTake(pdTRUE, portMAX_DELAY);

        if (notificationCount > 0U)
        {
            printf("eGTM TOM timer interrupt notified print task\r\n");
        }
    }
}

/*******************************************************************************
* Function Name: init_egtm_tom_timer
********************************************************************************
* Summary:
* Initialize the eGTM TOM timer used to periodically notify the print task.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
static void init_egtm_tom_timer(void)
{
    IfxEgtm_Tom_Timer_Config timerConfig;

    /* Enable the eGTM module */
    IfxEgtm_enable(&MODULE_EGTM);

    /* Initialize the timer configuration with defaults */
    IfxEgtm_Tom_Timer_initConfig(&timerConfig, &MODULE_EGTM);

    /* Configure the TOM timer channel, clock source, frequency, and interrupt */
    timerConfig.cluster               = TOM_TIMER_CLUSTER;
    timerConfig.timerChannel          = TOM_TIMER_CHANNEL;
    timerConfig.clock                 = IfxEgtm_Tom_Ch_ClkSrc_cmuFxclk4;
    timerConfig.frequency             = TOM_TIMER_FREQUENCY_HZ;
    timerConfig.interrupt.isrPriority = TOM_TIMER_ISR_PRIORITY;
    timerConfig.interrupt.isrProvider = IfxSrc_Tos_cpu0;

    /* Enable the FXCLK chain, then initialize and start the TOM timer */
    IfxEgtm_Cmu_enableClocks(&MODULE_EGTM, IFXEGTM_CMU_CLKEN_FXCLK);
    IfxEgtm_Tom_Timer_init(&g_timerDriver, &timerConfig);
    IfxEgtm_Tom_Timer_run(&g_timerDriver);
}

/*******************************************************************************
* Function Name: egtm_tom_timer_isr
********************************************************************************
* Summary:
* Handle the eGTM TOM timer interrupt and wake the print task.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
void egtm_tom_timer_isr(void)
{
    BaseType_t xHigherPriorityTaskWoken = pdFALSE;

    if (IfxEgtm_Tom_Timer_acknowledgeTimerIrq(&g_timerDriver) != FALSE)
    {
        if (g_printTaskHandle != NULL)
        {
            vTaskNotifyGiveFromISR(g_printTaskHandle, &xHigherPriorityTaskWoken);
            portYIELD_FROM_ISR(xHigherPriorityTaskWoken);
        }
    }
}
