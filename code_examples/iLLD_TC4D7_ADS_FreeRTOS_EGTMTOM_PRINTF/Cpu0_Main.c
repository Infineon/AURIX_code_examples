#include "FreeRTOS.h"
#include "task.h"
#include <stdio.h>

#include "demo_led_button.h"
#include "demo_print_timer.h"

#include "bsp/kit_tc4d7_lite.h"

#include "Cpu/Std/IfxCpu.h"
#include "Wtu/Std/IfxWtu.h"

#include "retarget_io/retarget_io.h"


/*******************************************************************************
* Macros
*******************************************************************************/
#define BLINKY_TASK_STACK_SIZE          (configMINIMAL_STACK_SIZE)
#define PRINT_TASK_STACK_SIZE           (configMINIMAL_STACK_SIZE * 2U)
#define BLINKY_TASK_PRIORITY            (tskIDLE_PRIORITY + 1U)
#define PRINT_TASK_PRIORITY             (tskIDLE_PRIORITY + 2U)

#define DEBUG_UART_BAUDRATE             115200U


/*******************************************************************************
* Type definitions
*******************************************************************************/

/*******************************************************************************
* Function Prototypes
*******************************************************************************/
static void init_board_io(void);
static void init_debug_uart(void);

/*******************************************************************************
* Function Name: core0_main
********************************************************************************
* Summary:
* This is the main function for core0.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
void core0_main(void)
{
    TaskHandle_t printTaskHandle = NULL;

    IfxCpu_enableInterrupts();
    
    /* !!WATCHDOG0 AND SAFETY WATCHDOG ARE DISABLED HERE!!
     * Enable the watchdogs and service them periodically if it is required
     */
    IfxWtu_disableCpuWatchdog(IfxWtu_getCpuWatchdogPassword());
    IfxWtu_disableSystemWatchdog(IfxWtu_getSystemWatchdogPassword());
    
    /**************************************************************************************************/
    /* Board resources initialization */

    init_board_io();
    init_debug_uart();

    /**************************************************************************************************/
    /* Demo execution */

    printf("******** TC4D7_lite_kit: FreeRTOS eGTM TOM Printf Code Example ********\r\n\n");

    BaseType_t xReturned = xTaskCreate(handle_led_and_button_task,
                                       "Blinky",
                                       BLINKY_TASK_STACK_SIZE,
                                       NULL,
                                       BLINKY_TASK_PRIORITY,
                                       NULL);
    IFX_ASSERT(IFX_VERBOSE_LEVEL_ERROR, xReturned == pdPASS);

    xReturned = xTaskCreate(handle_print_notification_task,
                            "Print",
                            PRINT_TASK_STACK_SIZE,
                            NULL,
                            PRINT_TASK_PRIORITY,
                            &printTaskHandle);
    IFX_ASSERT(IFX_VERBOSE_LEVEL_ERROR, xReturned == pdPASS);

    demo_print_timer_set_task_handle(printTaskHandle);

    demo_print_timer_init();

    vTaskStartScheduler();

    /* Should never reach here. */
    for ( ; ; )
    {
    }
}

/*******************************************************************************
* Function Name: init_board_io
********************************************************************************
* Summary:
* Initialize board IO used by the demo.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
static void init_board_io(void)
{
    IfxPort_setPinHigh(BOARD_USER_LED_1.port, BOARD_USER_LED_1.pinIndex);
    IfxPort_setPinLow(BOARD_USER_LED_2.port, BOARD_USER_LED_2.pinIndex);

    IfxPort_setPinModeOutput(BOARD_USER_LED_1.port,
                             BOARD_USER_LED_1.pinIndex,
                             IfxPort_OutputMode_pushPull,
                             IfxPort_OutputIdx_general);
    IfxPort_setPinModeOutput(BOARD_USER_LED_2.port,
                             BOARD_USER_LED_2.pinIndex,
                             IfxPort_OutputMode_pushPull,
                             IfxPort_OutputIdx_general);
    IfxPort_setPinModeInput(BOARD_USER_BUTTON_1.port,
                            BOARD_USER_BUTTON_1.pinIndex,
                            IfxPort_InputMode_pullUp);
}

/*******************************************************************************
* Function Name: init_debug_uart
********************************************************************************
* Summary:
* Initialize the debug UART used by the demo.
*
* Parameters:
*  none
*
* Return:
*  none
*
*******************************************************************************/
static void init_debug_uart(void)
{
    if (retarget_io_init(&BOARD_DEBUG_UART_TX, &BOARD_DEBUG_UART_RX, DEBUG_UART_BAUDRATE) != 0)
    {
        IFX_ASSERT(IFX_VERBOSE_LEVEL_ERROR, 0);
    }
}

